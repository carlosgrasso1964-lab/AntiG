    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        if (tfCodPrin.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Informe o Código Principal a ser excluído.");
            return;
        }

        try {
            Connection con = Conexao.faz_conexao();
            if (con == null) {
                JOptionPane.showMessageDialog(null, "Falha na conexão com o banco!");
                return;
            }

            // Verificar se há registros dependentes em tbclifor
            String sqlCheckDependents = "SELECT COUNT(*) FROM tbclifor WHERE fkCliForGp = ?";
            PreparedStatement checkStmt = con.prepareStatement(sqlCheckDependents);
            checkStmt.setString(1, tfCodPrin.getText().trim());
            ResultSet rs = checkStmt.executeQuery();
            rs.next();
            int count = rs.getInt(1);
            checkStmt.close();

            if (count > 0) {
                JOptionPane.showMessageDialog(null, "Não é possível excluir: o código está vinculado a " + count + " registro(s) em tbclifor.");
                con.close();
                return;
            }

            // Se não houver dependentes, prosseguir com o DELETE
            String sql = "DELETE FROM gpprincipal WHERE cod_Geral = ?";
            PreparedStatement stmt = con.prepareStatement(sql);
            stmt.setString(1, tfCodPrin.getText().trim());
            int rowsAffected = stmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(null, "Conta excluída com sucesso!");
                tfCodPrin.setText("");
                tfContaPrincipal.setText("");
                tfContaSecundaria.setText("");
                tfContaMovimento.setText("");
                tfBusca.setText("");
            } else {
                JOptionPane.showMessageDialog(null, "Nenhum registro foi excluído!");
            }

            stmt.close();
            con.close();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Erro ao excluir: " + ex.getMessage());
            Logger.getLogger(VCadPlaCon.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

