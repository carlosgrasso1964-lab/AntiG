    private void jButtonPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPesquisarActionPerformed
        try {
            DecimalFormat df = new DecimalFormat("#,##0.00");
            DecimalFormatSymbols symbols = new DecimalFormatSymbols();
            symbols.setDecimalSeparator(',');
            symbols.setGroupingSeparator('.');
            df.setDecimalFormatSymbols(symbols);

            Date dataSistema = new Date();
            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy - HH:mm:ss");
            jLabelDataH.setText(formato.format(dataSistema));

            Connection con = Conexao.faz_conexao();

            // === 1. CONSULTA PRINCIPAL: SALDOS POR RECURSO (excluindo empréstimos) ===
            String sql = """
            SELECT principal, subprincipal, conta, Fonte, vrecurso, recurso, saldos
            FROM vsaldos
            WHERE recurso NOT IN (
                SELECT DISTINCT recurso
                FROM view_movimento
                WHERE classif IN ('2.001.004', '2.002.001', '4.008.011')
                  AND COALESCE(Prev, '') <> 'F'
            )
            ORDER BY 
                CAST(SUBSTR(vrecurso, 1, 1) AS UNSIGNED), vrecurso, principal, subprincipal, conta
            """;

            PreparedStatement stmt = con.prepareStatement(sql);
            ResultSet rs = stmt.executeQuery();

            // === 2. SALDO DE EMPRÉSTIMOS (sinal negativo) ===
            String sqlEmprestimos = """
            SELECT 
                (COALESCE(SUM(CASE WHEN classif = '3.003.005' AND dtApr IS NOT NULL THEN Valor ELSE 0 END), 0) +
                COALESCE(SUM(CASE WHEN classif = '4.008.011' AND dtApr IS NOT NULL THEN Valor ELSE 0 END), 0)) * -1 
                AS saldo_emprestimos
            FROM view_movimento
            WHERE COALESCE(Prev, '') <> 'F'
            """;
            PreparedStatement stmtEmp = con.prepareStatement(sqlEmprestimos);
            ResultSet rsEmp = stmtEmp.executeQuery();
            double saldoEmprestimos = rsEmp.next() ? rsEmp.getDouble("saldo_emprestimos") : 0.0;
            rsEmp.close();
            stmtEmp.close();

            // === CONFIGURAR TABELA ===
            DefaultTableModel modelo = (DefaultTableModel) jTablePesquisa.getModel();
            modelo.setNumRows(0);
            jTablePesquisa.setAutoResizeMode(JTable.AUTO_RESIZE_OFF);

            // Larguras das colunas
            jTablePesquisa.getColumnModel().getColumn(0).setPreferredWidth(75);  // Principal
            jTablePesquisa.getColumnModel().getColumn(1).setPreferredWidth(180); // Sub
            jTablePesquisa.getColumnModel().getColumn(2).setPreferredWidth(240); // Conta
            jTablePesquisa.getColumnModel().getColumn(3).setPreferredWidth(320); // Fonte
            jTablePesquisa.getColumnModel().getColumn(4).setPreferredWidth(100); // vrecurso
            jTablePesquisa.getColumnModel().getColumn(5).setPreferredWidth(75);  // recurso
            jTablePesquisa.getColumnModel().getColumn(6).setPreferredWidth(100); // Saldo
            jTablePesquisa.getColumnModel().getColumn(7).setPreferredWidth(140); // Acumulado

            DefaultTableCellRenderer rightRenderer = new DefaultTableCellRenderer();
            rightRenderer.setHorizontalAlignment(SwingConstants.RIGHT);
            jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(rightRenderer);
            jTablePesquisa.getColumnModel().getColumn(7).setCellRenderer(rightRenderer);

            // === PREENCHER TABELA ===
            double sa = 0.0;
            String prin = "", sub = "", cta = "";

            while (rs.next()) {
                double saldoAtual = rs.getDouble("saldos");
                sa += saldoAtual;

                String novoPrin = rs.getString("principal");
                String novoSub = rs.getString("subprincipal");
                String novaCta = rs.getString("conta");

                // Só mostra o principal/sub/conta na primeira ocorrência
                if (!novoPrin.equals(prin)) {
                    prin = novoPrin;
                } else {
                    prin = "";
                }

                if (!novoSub.equals(sub)) {
                    sub = novoSub;
                } else {
                    sub = "";
                }

                if (!novaCta.equals(cta)) {
                    cta = novaCta;
                    modelo.addRow(new Object[]{"", "", "", "", "", "", "", ""}); // Linha em branco
                } else {
                    cta = "";
                }

                modelo.addRow(new Object[]{
                    prin,
                    sub,
                    cta,
                    rs.getString("Fonte"),
                    rs.getString("vrecurso"),
                    rs.getString("recurso"),
                    df.format(saldoAtual),
                    df.format(sa)
                });

                // Atualiza para próxima iteração
                prin = novoPrin;
                sub = novoSub;
                cta = novaCta;
            }

            // === LINHA EM BRANCO + EMPRÉSTIMOS ===
            modelo.addRow(new Object[]{"", "", "", "", "", "", "", ""});
            modelo.addRow(new Object[]{"", "", "", "Empréstimos (saldo)", "", "",
                df.format(saldoEmprestimos),
                df.format(sa + saldoEmprestimos)
            });

            // === CORES NA COLUNA DE SALDO ===
            jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(new CustomTableCellRenderer(6, 11, false));

            // === FECHAR RECURSOS ===
            rs.close();
            stmt.close();
            con.close();

        } catch (SQLException ex) {
            Logger.getLogger(VConsSaldos.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(null, "Erro ao consultar saldos: " + ex.getMessage());
        } finally {
            try {
                Conexao.faz_conexao().close();
            } catch (Exception e) {
            }
        }
    }//GEN-LAST:event_jButtonPesquisarActionPerformed

    private void jButtonPImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPImprimirActionPerformed
        DateFormat dateFormat = new SimpleDateFormat("dd/MM/yyyy HH:mm:ss");
        Date date = new Date();
        String infDt = dateFormat.format(date);
        PrintRequestAttributeSet set = new HashPrintRequestAttributeSet();
        set.add(OrientationRequested.LANDSCAPE);
        MessageFormat cabecalho = new MessageFormat("Relatório de Consulta - Saldos - " + infDt);
        MessageFormat rodape = new MessageFormat("Página {0,number,integer}");
        try {
            //jTablePesquisa.print(JTable.PrintMode.FIT_WIDTH, cabecalho, rodape);
            jTablePesquisa.print(JTable.PrintMode.FIT_WIDTH, cabecalho, rodape, false, set, false);
        } catch (java.awt.print.PrinterException e) {
            System.err.format("Erro ao imprimir - Consulta Saldos!!! %s%n", e.getMessage());
        }
    }//GEN-LAST:event_jButtonPImprimirActionPerformed

