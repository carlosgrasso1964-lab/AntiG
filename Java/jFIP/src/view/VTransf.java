    /**
     * Garante que exista um clifor com o codigo do recurso (padrao da transferencia).
     * Se nao existir, cria automaticamente para evitar erro de FK 1452.
     */
    private void garantirClifor(Connection con, String codigoRecurso, String fkGpprinc) throws SQLException {
        String sqlChk = "SELECT COUNT(*) FROM tbclifor WHERE codCliFor = ?";
        try (PreparedStatement chk = con.prepareStatement(sqlChk)) {
            chk.setString(1, codigoRecurso);
            try (ResultSet rs = chk.executeQuery()) {
                if (rs.next() && rs.getInt(1) > 0) {
                    return; // ja existe
                }
            }
        }
        String tipo = "FOR";
        if (fkGpprinc != null && fkGpprinc.startsWith("2.001.003")) {
            tipo = "CAR";
        } else if (fkGpprinc != null && fkGpprinc.startsWith("1.001.001")) {
            tipo = "BCO";
        }
        String nome = codigoRecurso;
        String sqlNome = "SELECT nomebco FROM tbrecursos WHERE codigo = ?";
        try (PreparedStatement st = con.prepareStatement(sqlNome)) {
            st.setString(1, codigoRecurso);
            try (ResultSet rs = st.executeQuery()) {
                if (rs.next()) {
                    nome = rs.getString(1);
                }
            }
        }
        String sqlIns = "INSERT INTO tbclifor (codCliFor, Tipo, nomeCliFor, apelidoCliFor, contatoCliFor, obs, fkCliForGp) VALUES (?,?,?,?,?,?,?)";
        try (PreparedStatement ins = con.prepareStatement(sqlIns)) {
            ins.setString(1, codigoRecurso);
            ins.setString(2, tipo);
            ins.setString(3, nome);
            ins.setString(4, nome);
            ins.setString(5, "-");
            ins.setString(6, "-");
            ins.setString(7, fkGpprinc);
            ins.executeUpdate();
        }
    }

private static class CarregarCbxO {

        @SuppressWarnings({"empty-statement", "unchecked"})
        public void CarregarCbxO(String tabela, String valor, JComboBox combo) throws SQLException {
            String sql = "Select * FROM " + tabela + " ORDER BY nomebco";
            Connection con = Conexao.faz_conexao();
            try {
                PreparedStatement stmt = con.prepareStatement(sql);
                try (ResultSet rs = stmt.executeQuery()) {
                    while (rs.next()) {
                        combo.addItem(rs.getString(valor) + "-" + (rs.getString("codigo") + "-" + (rs.getString("fk_gpprinc"))));
                    }
                }
                con.close();
            } catch (SQLException ex) {
                Logger.getLogger(VTransf.class
                        .getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

