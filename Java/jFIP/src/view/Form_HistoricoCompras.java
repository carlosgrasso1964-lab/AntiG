    public void carregarCompras() throws ParseException {

        try {
            ComprasDAO dao = new ComprasDAO();
            List<Compras> lista = dao.listarCompras();

            DefaultTableModel model = (DefaultTableModel) tabela.getModel();
            model.setRowCount(0);

            NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));
            double acumulado = 0;

            for (Compras c : lista) {
                acumulado += c.getTotalCompra();

                // CONVERSÃO PERFEITA DE TIMESTAMP ? String dd/MM/yyyy
                String dataFormatada = "Data inválida";
                if (c.getDataCompra() != null) {
                    LocalDate data = c.getDataCompra()
                            .toInstant()
                            .atZone(ZoneId.systemDefault())
                            .toLocalDate();
                    dataFormatada = data.format(DateTimeFormatter.ofPattern("dd/MM/yyyy"));
                }

                model.addRow(new Object[]{
                    c.getId(),
                    c.getFornecedor().getNomeCliFor(),
                    dataFormatada,
                    nf.format(c.getTotalCompra()),
                    nf.format(acumulado),
                    c.getObservacoes() != null ? c.getObservacoes() : ""
                });
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar histórico de compras:\n" + ex.getMessage(),
                    "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

