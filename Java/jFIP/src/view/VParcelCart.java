    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed
        int Parcelas = Integer.parseInt(jTextFieldParcelas.getText());  //Número de Parcelas
        BigDecimal Princ = BigDecimal.ZERO;
        BigDecimal LiqParc = BigDecimal.ZERO;
        BigDecimal difer = BigDecimal.ZERO;
        BigDecimal comparaCompra = new BigDecimal(jTextFieldVrCompra.getText().replaceAll(",", "."));
        int i = 0;
        int idsc = 0;
        if (comparaCompra.compareTo(BigDecimal.ZERO) == 0) {
            BigDecimal vrParcela = new BigDecimal(jTextFieldVrParcela.getText());
            Princ = vrParcela.multiply(new BigDecimal(Parcelas));
            LiqParc = vrParcela;
        } else {
            Princ = new BigDecimal(jTextFieldVrCompra.getText().replaceAll(",", "."));
            BigDecimal meValor = Princ.divide(new BigDecimal(Parcelas), 10, RoundingMode.HALF_UP); // Divisão com precisão extra
            BigDecimal Valor = meValor.setScale(2, RoundingMode.FLOOR);
            LiqParc = Valor;

            BigDecimal vrParcD;
            BigDecimal pc = new BigDecimal(Parcelas); // Atribuo o pc com a variável Parcelas
            vrParcD = Princ.subtract(Valor.multiply(pc)).setScale(2, RoundingMode.FLOOR);
            difer = vrParcD;

            // Verifica se há diferença (positiva ou negativa)
            if (difer.compareTo(BigDecimal.ZERO) != 0) {
                String msg = "Diferença de " + difer + " encontrada.\n"
                        + "Em qual parcela (1 a " + Parcelas + ") deseja lançar?";

                String escolha = JOptionPane.showInputDialog(null, msg);

                try {
                    if (escolha != null && !escolha.isEmpty()) {
                        idsc = Integer.parseInt(escolha);

                        // Valida se o número digitado está dentro do intervalo real
                        if (idsc < 1 || idsc > Parcelas) {
                            idsc = 1; // Padrão caso digite fora do range
                            JOptionPane.showMessageDialog(null, "Parcela inválida! A diferença será lançada na parcela 1.");
                        }
                    } else {
                        // Se o usuário cancelar ou deixar vazio, assume a primeira parcela
                        idsc = 1;
                    }
                } catch (NumberFormatException e) {
                    // Se o usuário digitar letras em vez de números
                    idsc = 1;
                    JOptionPane.showMessageDialog(null, "Entrada inválida. A diferença será lançada na parcela 1.");
                }
            }
        }

        String opc = buttonGroup1.getSelection().getActionCommand();

        Object[] options = {"Sim", "Não"};
        int i1 = JOptionPane.showOptionDialog(null, "Corrige Data da Emissão?", "Corrige Emissão",
                JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE, null, options, options[0]);

        boolean corrigeEmi = (i1 == JOptionPane.YES_OPTION);
        SimpleDateFormat dateFormat = new SimpleDateFormat("dd/MM/yyyy");

        try (Connection con = Conexao.faz_conexao()) { // Uma única conexão para todas as parcelas

            // Criamos calendários baseados nos campos de texto ANTES do loop
            Calendar calEmi = Calendar.getInstance();
            Calendar calVcto = Calendar.getInstance();
            calEmi.setTime(dateFormat.parse(jFormattedTextFieldEmissao.getText()));
            calVcto.setTime(dateFormat.parse(jFormattedTextFieldVencimento.getText()));

            con.setAutoCommit(false);
            try {
                for (i = 0; i < Parcelas; i++) {
                    // Se não for a primeira parcela, incrementamos as datas
                    if (i > 0) {
                        int field = Calendar.MONTH;
                        int amount = 0;

                        // Usando .equals para comparação de String
                        if ("1".equals(opc)) {
                            amount = 1;      // Mensal
                        } else if ("2".equals(opc)) {
                            amount = 3; // Trimestral
                        } else if ("3".equals(opc)) {
                            amount = 2; // Bimestral
                        } else if ("4".equals(opc)) {
                            field = Calendar.YEAR;
                            amount = 1;
                        } // Anual
                        else if ("5".equals(opc)) {
                            field = Calendar.WEEK_OF_YEAR;
                            amount = 1;
                        } // Semanal
                        else if ("6".equals(opc)) {
                            field = Calendar.DAY_OF_MONTH;
                            amount = 1;
                        } // Diária
                        else if ("7".equals(opc)) {
                            amount = 4; // Quadrimestral
                        }
                        // Atualiza a data de Vencimento SEMPRE
                        calVcto.add(field, amount);

                        // Atualiza a data de Emissão SOMENTE se o usuário confirmou a correção
                        if (corrigeEmi) {
                            calEmi.add(field, amount);
                        }
                    }

                    // Converter para SQL Date
                    java.sql.Date sqlEmi = new java.sql.Date(calEmi.getTimeInMillis());
                    java.sql.Date sqlVcto = new java.sql.Date(calVcto.getTimeInMillis());

                    // --- INSERÇÃO 1 (Recurso) ---
                    executarInsert(con, sqlEmi, sqlVcto, i, Parcelas, LiqParc, difer, idsc, "1");

                    // --- INSERÇÃO 2 (Pagamento) ---
                    executarInsert(con, sqlEmi, sqlVcto, i, Parcelas, LiqParc, difer, idsc, "2");

                    // --- INSERÇÃO 3 (Cartão) ---
                    executarInsert(con, sqlEmi, sqlVcto, i, Parcelas, LiqParc, difer, idsc, "3");
                }
                con.commit(); // Só grava se tudo der certo
            } catch (Exception e) {
                con.rollback(); // Desfaz tudo se um único insert falhar
                throw e;
            }
            JOptionPane.showMessageDialog(null, "Parcelamento de cartões gerado com sucesso!");

            //Limpar dados dos campos
            jTextFieldVrCompra.setText("");
            jTextFieldParcelas.setText("");
            jTextFieldNrFav.setText("");
            jTextFieldClassFav.setText("");
            jTextFieldVClass.setText("");
            jTextFieldDoc.setText("");
            jFormattedTextFieldEmissao.setText("");
            jFormattedTextFieldVencimento.setText("");
            jTextFieldVrParcela.setText("");
            jTextFieldDescricao.setText("");
            jTextFieldStatus.setText("");
            jTextFieldPrev.setText("");
            jComboBoxClass.setSelectedIndex(0);
            jComboBoxFav.setSelectedIndex(0);

        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Erro: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonGerarActionPerformed

    // Método auxiliar corrigido e robusto
    private void executarInsert(Connection con, java.sql.Date dataEmi, java.sql.Date dataVcto,
            int i, int totalParc, BigDecimal liq, BigDecimal dif, int idsc, String tipoIns) throws SQLException {

        String sql = "INSERT INTO tbmovimento(recurso,vrecurso,clifor,vCliFor,dtlancto,dtEmi,dtVcto,documento,classif,Descr,valor,dtApr,statusMov,Prev) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)";

        try (PreparedStatement stmt = con.prepareStatement(sql)) {
            // 1. Lógica da Diferença: Aplica a diferença apenas na parcela escolhida (idsc)
            BigDecimal valorFinal = liq;
            if ((i + 1) == idsc) {
                valorFinal = liq.add(dif);
            }
            
            valorFinal = valorFinal.abs();
            
            // 2. Definição de Recurso e Valor (Sinal)
            // tipoIns: "1" = Recurso (Entrada/Positivo), "2" = Pagamento (Saída/Negativo), "3" = Cartão
            if (tipoIns.equals("1")) {
                stmt.setString(1, "0079");
                stmt.setString(2, "2.001.003");
                stmt.setBigDecimal(11, valorFinal.negate()); // Positivo
            } else if (tipoIns.equals("2")) {
                stmt.setString(1, "0079");
                stmt.setString(2, "2.001.003");
                // Se for pagamento, forçamos o valor a ser negativo para o caixa
                stmt.setBigDecimal(11, valorFinal.abs());
            } else { // Cartão (tipo "3")
                stmt.setString(1, tfNrRecurso.getText());
                stmt.setString(2, "2.001.003");
                stmt.setBigDecimal(11, valorFinal.negate());
            }

            // 3. Campos Comuns
            stmt.setString(3, jTextFieldNrFav.getText());
            stmt.setString(4, jTextFieldClassFav.getText());
            stmt.setDate(5, dataEmi);  // dtlancto
            stmt.setDate(6, dataEmi);  // dtEmi
            stmt.setDate(7, dataVcto); // dtVcto
            stmt.setString(8, jTextFieldDoc.getText());

            // Classificação: Se for o registro principal (1), usa o do campo, senão usa a padrão
            stmt.setString(9, tipoIns.equals("1") ? jTextFieldVClass.getText() : "9.001.003");

            // Descrição com contador de parcelas
            stmt.setString(10, "parc." + (i + 1) + "/" + totalParc + " - " + jTextFieldDescricao.getText());

            // 4. Lógica da Data de Aprovação (dtApr) e Status
            if (tipoIns.equals("3")) {
                // Cartão não costuma ter data de aprovação imediata no seu modelo
                stmt.setNull(12, java.sql.Types.DATE);
                stmt.setString(13, ""); // Status vazio para cartão
            } else {
                // Recurso e Pagamento entram como liquidados (PG)
                stmt.setDate(12, dataVcto);
                stmt.setString(13, "PG");
            }

            stmt.setString(14, jTextFieldPrev.getText());

            // Executa a inserção
            stmt.executeUpdate();
        }
    }

