        atualizarCampo(txtDDespFix, despFixas);
        atualizarCampo(txtDComiss, percComissoes);
        atualizarCampo(txtDVerbasPubl, percPublicidade);
        atualizarCampo(txtDAdm, percDespAdministrativas);
        atualizarCampo(txtMEmprest, emprestimos);
        atualizarCampo(txtDEmprest, emprestimos);

