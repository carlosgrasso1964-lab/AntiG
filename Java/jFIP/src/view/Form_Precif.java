        BigDecimal despFixas = converterParaBigDecimal(txtDespFixas);
        BigDecimal custoMercadoria = converterParaBigDecimal(txtCustos);
        BigDecimal percComissoes = converterParaBigDecimal(txtComissoes);
        BigDecimal percPublicidade = converterParaBigDecimal(txtPublicidade);
        BigDecimal percDespAdministrativas = converterParaBigDecimal(txtDespAdministrativas);
        BigDecimal percImpostos = converterParaBigDecimal(txtImpostos);
        BigDecimal emprestimos = converterParaBigDecimal(txtValorEmprest);

