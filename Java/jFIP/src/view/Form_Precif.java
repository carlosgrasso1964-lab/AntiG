    private void jButtonSimularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSimularActionPerformed
        //System.out.println("Botão Simular pressionado!");

        if (!calculoRealizado) {
            JOptionPane.showMessageDialog(null, "Você precisa calcular antes de simular!", "Aviso", JOptionPane.WARNING_MESSAGE);
            //System.out.println("Cálculo ainda não foi realizado. Abortando...");
            return;
        }

        try {
            if (txtMCustos.getText().isEmpty() || txtMDespFix.getText().isEmpty() || txtMPercGastosVar.getText().isEmpty()
                    || txtLucroLDesejado.getText().isEmpty() || txtMPercImpSFat.getText().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Todos os campos devem estar preenchidos!", "Erro", JOptionPane.ERROR_MESSAGE);
                //System.out.println("Erro: Campos vazios detectados.");
                return;
            }

            //System.out.println("Campos preenchidos. Iniciando conversão...");

            NumberFormat nf = NumberFormat.getInstance(Locale.getDefault());

            // Conversão dos valores
            double custos = nf.parse(txtMCustos.getText()).doubleValue();
            double despesasFixas = nf.parse(txtMDespFix.getText()).doubleValue();
            double percDespesasVariaveis = nf.parse(txtMPercGastosVar.getText()).doubleValue() / 100;  // Correção: dividir por 100
            double percLucroLiquido = nf.parse(txtLucroLDesejado.getText()).doubleValue() / 100;  // Correção: dividir por 100
            double percImposto = nf.parse(txtMPercImpSFat.getText()).doubleValue() / 100;  // Correção: dividir por 100

            //System.out.println("Custos: " + custos);
            //System.out.println("Despesas Fixas: " + despesasFixas);
            //System.out.println("Despesas Variáveis (%): " + percDespesasVariaveis);
            //System.out.println("Lucro Líquido (%): " + percLucroLiquido);
            //System.out.println("Percentual Imposto (%): " + percImposto);

            double somaPercentuais = percDespesasVariaveis + percLucroLiquido + percImposto;
            //System.out.println("Soma Percentuais: " + somaPercentuais);

            if (somaPercentuais >= 1) {
                JOptionPane.showMessageDialog(null, "A soma dos percentuais não pode ser maior ou igual a 100%!", "Erro", JOptionPane.ERROR_MESSAGE);
                //System.out.println("Erro: Soma dos percentuais >= 100%.");
                return;
            }

            // Fórmula corrigida
            double faturamentoNecessario = (despesasFixas + custos) / (1 - somaPercentuais);

            //System.out.println("Faturamento Necessário calculado: " + faturamentoNecessario);

            DecimalFormat df = new DecimalFormat("#,##0.00");
            JOptionPane.showMessageDialog(null, "Faturamento Necessário: R$ " + df.format(faturamentoNecessario),
                    "Resultado", JOptionPane.INFORMATION_MESSAGE);
        } catch (NumberFormatException | ParseException e) {
            JOptionPane.showMessageDialog(null, "Por favor, insira valores válidos!", "Erro", JOptionPane.ERROR_MESSAGE);
            //System.out.println("Erro de conversão: " + e.getMessage());
        }
    }//GEN-LAST:event_jButtonSimularActionPerformed

