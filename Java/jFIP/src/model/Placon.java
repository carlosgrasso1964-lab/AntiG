public class Placon {
  
  private String cod_Geral;
  private String nome_P;
  private String nome_S;
  private String nome_C;

    public String getCod_Geral() {
        return cod_Geral;
    }

    public void setCod_Geral(String cod_Geral) {
        this.cod_Geral = cod_Geral;
    }

    public String getNome_P() {
        return nome_P;
    }

    public void setNome_P(String nome_P) {
        this.nome_P = nome_P;
    }

    public String getNome_S() {
        return nome_S;
    }

    public void setNome_S(String nome_S) {
        this.nome_S = nome_S;
    }

    public String getNome_C() {
        return nome_C;
    }

    public void setNome_C(String nome_C) {
        this.nome_C = nome_C;
    }
  
}
