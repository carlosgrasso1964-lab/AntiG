    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed

        try {

            // Aqui seleciono a opção desejada para a divisão das parcelas
            String opc = buttonGroup1.getSelection().getActionCommand();

            switch (opc) {

                case "1" ->

                    System.out.println("Escolhida Mensal");

                case "2" ->

                    System.out.println("Escolhida Trimestral");

                case "3" ->

                    System.out.println("Escolhida Bimestral");

                case "4" ->

                    System.out.println("Escolhida Anual");

                case "5" ->

                    System.out.println("Escolhida Semanal");

                case "6" ->

                    System.out.println("Escolhida Diária");

                case "7" ->

                    System.out.println("Escolhida Quadrimestral");

                default ->

                    System.out.println("Escolhida opção inválida! Escolha entre a 1 e 7");

            }

            //Aqui criamos a opção corrige para atribuirmos sim(S) ou não(N)
            String corrige;

            Object[] options = {"Sim", "Não"};

            // Aqui armazeno em corrige para saber se corrigimos a data de emissïão também de acordo com a opção escolhida
            int i1 = JOptionPane.showOptionDialog(null, "Corrige Data da Emissão? !!", "Corrige Emissão",
                    JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE, null, options, options[0]);

            corrige = i1 == JOptionPane.YES_OPTION ? "S" : "N";

            int parcelas = Integer.parseInt(jTextFieldParcelas.getText());

            BigDecimal valorCompra = new BigDecimal(jTextFieldVrCompra.getText().replace(",", "."));

            BigDecimal valorParcela = new BigDecimal(jTextFieldVrParcela.getText().replace(",", "."));

            String tipoSelecionado = jCbxTipo.getSelectedItem().toString();

            String tipo = tipoSelecionado.substring(0, 1);

            String cliforn = jTextFieldNrFav.getText();

            String vcliforn = jTextFieldClassFav.getText();

            String documento = jTextFieldDoc.getText();

            String classif = jTextFieldVClass.getText();

            String descricao = jTextFieldDescricao.getText();

            String status = jTextFieldStatus.getText();

            String prev = jTextFieldPrev.getText();

            String emissao = jFormattedTextFieldEmissao.getText();

            String vcto = jFormattedTextFieldVencimento.getText();

            ParcelamentoController controller = new ParcelamentoController();

            controller.gerarParcelas(parcelas, valorCompra, valorParcela, tipo, cliforn, vcliforn, documento, classif, descricao, status, prev, opc, corrige, emissao, vcto);

            JOptionPane.showMessageDialog(this, "Parcelamento gerado com sucesso!");

            limparCampos();

        } catch (HeadlessException | NumberFormatException | SQLException e) {

            JOptionPane.showMessageDialog(this, "Erro ao gerar parcelamento: " + e.getMessage());

        } catch (ParseException ex) {

            Logger.getLogger(Tela_de_Parcelamento.class.getName()).log(Level.SEVERE, null, ex);

        }
    }//GEN-LAST:event_jButtonGerarActionPerformed

