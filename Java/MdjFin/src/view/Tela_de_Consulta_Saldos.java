    @SuppressWarnings("unchecked")
    private void jButtonPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPesquisarActionPerformed
        try {
            DecimalFormat df = new DecimalFormat("#,##0.00");
            Date dataSistema = new Date();
            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy - HH:mm:ss");
            jLabelDataH.setText(formato.format(dataSistema));
            Connection con;
            con = Conexao.faz_conexao();
            String sql;
            sql = "SELECT * FROM view_saldos";
            PreparedStatement stmt = con.prepareStatement(sql);
            try (ResultSet rs = stmt.executeQuery()) {
                DefaultTableModel modelo = (DefaultTableModel) jTablePesquisa.getModel();
                modelo.setNumRows(0);
                jTablePesquisa.setRowSorter(new TableRowSorter(modelo)); // Organiza tabela clicando no tÃ­tulo da coluna
                jTablePesquisa.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF);
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(0)).setPreferredWidth(90); //Principal
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(1)).setPreferredWidth(180); //Sub
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(2)).setPreferredWidth(240); //Conta
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(3)).setPreferredWidth(300); //Fonte
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(4)).setPreferredWidth(100); //nr_Conta
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(5)).setPreferredWidth(75);//id_Recurso
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(6)).setPreferredWidth(100);//Saldo
                jTablePesquisa.getColumn(jTablePesquisa.getColumnName(7)).setPreferredWidth(100);//Acumulado
                DefaultTableCellRenderer tab = new DefaultTableCellRenderer();
                tab.setHorizontalAlignment(SwingConstants.RIGHT);
                jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(tab);
                jTablePesquisa.getColumnModel().getColumn(7).setCellRenderer(tab);
                Double sa = 0.00;
                String prin, sub, cta;
                prin = " ";
                sub = " ";
                cta = " ";
                while (rs.next()) {
                    sa = sa + rs.getDouble("saldos");
                    if (prin.equals(rs.getString("principal"))) {
                        prin = " ";
                    } else {
                        prin = rs.getString("principal");
                    }
                    
                    if (sub.equals(rs.getString("subprincipal"))) {
                        sub = " ";
                    } else {
                        sub = rs.getString("subprincipal");
                    }
                    
                    if (cta.equals(rs.getString("conta"))) {
                        cta = " ";
                    } else {
                        cta = rs.getString("conta");
                        modelo.addRow(new Object[]{"", "", "", "", "", "", 0});
                    }
                    modelo.addRow(new Object[]{
                        prin,
                        sub,
                        cta,
                        rs.getString("Fonte"),
                        rs.getString("vrecurso"),
                        rs.getString("recurso"),
                        df.format(rs.getDouble("saldos")),
                        df.format(sa),});
                    prin = rs.getString("principal");
                    sub = rs.getString("subprincipal");
                    cta = rs.getString("conta");
                }   //Parâmetros Coluna da jTable, Tamanho da Fonte, se é data (true ou false).
                jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(new CustomTableCellRenderer(6, 11, false));
            }
            con.close();
        } catch (SQLException ex) {
            Logger.getLogger(Tela_de_Mov.class
                    .getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButtonPesquisarActionPerformed

