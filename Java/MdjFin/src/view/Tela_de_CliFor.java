    private Placon buscarGrupoPrincipal(String cod) {
        if (cod == null || cod.trim().isEmpty()) {
            return null;
        }
        try {
            return dao.buscarGrupoPrincipal(cod.trim());
        } catch (SQLException ex) {
            Logger.getLogger(Tela_de_CliFor.class.getName()).log(Level.SEVERE, null, ex);
            return null;
        }
    }


