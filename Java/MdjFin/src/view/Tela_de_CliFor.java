    public void listar() {
        try {
            // 1. DESATIVA O SORTER ANTES DE MEXER NO MODEL
            tbDadosCliFor.setRowSorter(null);

            List<CliFor> lista = dao.listarTodos();
            DefaultTableModel model = (DefaultTableModel) tbDadosCliFor.getModel();
            model.setRowCount(0);

            for (CliFor c : lista) {
                model.addRow(new Object[]{
                    c.getCodCliFor(),
                    c.getTipo(),
                    c.getNomeCliFor(),
                    c.getApelidoCliFor() != null ? c.getApelidoCliFor() : "",
                    c.getEmail() != null ? c.getEmail() : "",
                    c.getCelular() != null ? c.getCelular() : "",
                    c.getTelefone() != null ? c.getTelefone() : "",
                    c.getCep() != null ? c.getCep() : "",
                    c.getEndereco() != null ? c.getEndereco() : "",
                    c.getNumero(),
                    c.getComplemento() != null ? c.getComplemento() : "",
                    c.getBairro() != null ? c.getBairro() : "",
                    c.getCidade() != null ? c.getCidade() : "",
                    c.getEstado() != null ? c.getEstado() : "",
                    c.getRg() != null ? c.getRg() : "",
                    c.getCpf() != null ? c.getCpf() : "",
                    c.getContatoCliFor() != null ? c.getContatoCliFor() : "",
                    c.getObs() != null ? c.getObs() : "",
                    c.getFkCliForGp() != null ? c.getFkCliForGp().getCod_Geral() : ""
                });
            }

            // 2. Só REATIVA O SORTER DEPOIS DE TERMINAR TUDO
            tbDadosCliFor.setRowSorter(new TableRowSorter<>(model));

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar lista: " + ex.getMessage());
        }
    }

