    private void adicionarListeners() {
        // Sugere código automático ao mudar tipo (só quando Não está editando)
        jCbxTipo.addItemListener(e -> {
            if (e.getStateChange() == 1 && editingCodCliFor == null) {
                String tipo = (String) jCbxTipo.getSelectedItem();
                String novoCod = tipo.equals("CLI") ? dao.suggestClienteCode() : dao.suggestFornecedorCode();
                tfCodCliFor.setText(novoCod);
            }
        });

        // Preenche campos ao clicar na tabela
        tbDadosCliFor.getSelectionModel().addListSelectionListener((ListSelectionEvent e) -> {
            if (!e.getValueIsAdjusting() && tbDadosCliFor.getSelectedRow() != -1) {
                int row = tbDadosCliFor.getSelectedRow();
                tfCodCliFor.setText(getValue(row, 0));
                jCbxTipo.setSelectedItem(getValue(row, 1));
                tfNomeCliFor.setText(getValue(row, 2));
                tfNomeFant.setText(getValue(row, 3));
                txtEmail.setText(getValue(row, 4));
                txtCelular.setText(getValue(row, 5));
                txtTelefone.setText(getValue(row, 6));
                txtCep.setText(getValue(row, 7));
                txtEndereco.setText(getValue(row, 8));
                txtNumero.setText(getValue(row, 9));
                txtComplemento.setText(getValue(row, 10));
                txtBairro.setText(getValue(row, 11));
                txtCidade.setText(getValue(row, 12));
                cbUF.setSelectedItem(getValue(row, 13));
                txtRG.setText(getValue(row, 14));
                txtCpf.setText(getValue(row, 15));
                tfContato.setText(getValue(row, 16));
                tfObs.setText(getValue(row, 17));
                tfConta.setText(getValue(row, 18));

                editingCodCliFor = tfCodCliFor.getText();
                btSalvar.setEnabled(false);
            }
        });
    }

    private String getValue(int row, int col) {
        Object val = tbDadosCliFor.getValueAt(row, col);
        return val == null ? "" : val.toString();
    }

