        tbDadosCliFor.getColumnModel().getColumn(3).setPreferredWidth(200);  // apelido
        tbDadosCliFor.getColumnModel().getColumn(4).setPreferredWidth(180);  // email
        tbDadosCliFor.getColumnModel().getColumn(5).setPreferredWidth(120);  // celular
        tbDadosCliFor.getColumnModel().getColumn(12).setPreferredWidth(150); // cidade
        tbDadosCliFor.getColumnModel().getColumn(18).setPreferredWidth(100); // grupo

        // Ocultar colunas
        int[] colunasOcultas = {4, 6, 7, 8, 9, 10, 11, 14, 15, 17};
