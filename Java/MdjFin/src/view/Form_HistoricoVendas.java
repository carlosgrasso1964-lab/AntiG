    private void btnApurarLucroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApurarLucroActionPerformed
        try {
            LocalDate inicio = LocalDate.parse(txtInicio.getText().trim(),
                    DateTimeFormatter.ofPattern("dd/MM/yyyy"));
            LocalDate fim = LocalDate.parse(txtFim.getText().trim(),
                    DateTimeFormatter.ofPattern("dd/MM/yyyy"));

            try (Connection con = Conexao.faz_conexao()) {
                String sql = """
                SELECT 
                    DATE(v.data_venda) AS data,
                    SUM(iv.subtotal) AS faturado,
                    SUM(p.precoMedioCusto * iv.qtd) AS custo,
                    SUM(iv.subtotal - (p.precoMedioCusto * iv.qtd)) AS lucro
                FROM tb_vendas v
                INNER JOIN tb_itensvendas iv ON v.id = iv.venda_id
                INNER JOIN tb_produtos p ON iv.produto_id = p.id
                WHERE DATE(v.data_venda) BETWEEN ? AND ?
                GROUP BY DATE(v.data_venda)
                ORDER BY data
                """;

                try (PreparedStatement ps = con.prepareStatement(sql)) {
                    ps.setString(1, inicio.toString());
                    ps.setString(2, fim.toString());
                    try (ResultSet rs = ps.executeQuery()) {
                        gerarRelatorioLucro(rs, inicio, fim);
                    }
                }
            }
            JOptionPane.showMessageDialog(this, "Relatório de lucro gerado com sucesso!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnApurarLucroActionPerformed

    private void gerarPDFVendas(List<Vendas> lista, LocalDate inicio, LocalDate fim) throws Exception {
        String caminho = System.getProperty("user.home") + "/Desktop/Relatorio_Vendas_"
                + inicio.format(DateTimeFormatter.ofPattern("dd-MM-yyyy")) + "_a_"
                + fim.format(DateTimeFormatter.ofPattern("dd-MM-yyyy")) + ".pdf";

        Document doc = new Document();
        PdfWriter.getInstance(doc, new FileOutputStream(caminho));
        doc.open();

        // Título
        Paragraph titulo = new Paragraph("RELATÓRIO DE VENDAS",
                FontFactory.getFont(FontFactory.HELVETICA_BOLD, 16));
        titulo.setAlignment(Element.ALIGN_CENTER);
        doc.add(titulo);

        doc.add(new Paragraph("Período: " + inicio.format(DateTimeFormatter.ofPattern("dd/MM/yyyy"))
                + " a " + fim.format(DateTimeFormatter.ofPattern("dd/MM/yyyy"))));
        doc.add(new Paragraph("Gerado em: " + LocalDateTime.now().format(
                DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm"))));
        doc.add(new Paragraph(" "));

        // Tabela
        PdfPTable table = new PdfPTable(5);
        table.setWidthPercentage(100);
        table.setWidths(new float[]{10, 30, 15, 15, 30});

        table.addCell("ID");
        table.addCell("Cliente");
        table.addCell("Data");
        table.addCell("Valor");
        table.addCell("Obs");

        NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));
        double total = 0;

        for (Vendas v : lista) {
            total += v.getTotal_venda();
            String data = v.getData_venda() != null
                    ? v.getData_venda().toLocalDateTime().format(DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm")) : "";

            table.addCell(String.valueOf(v.getId()));
            table.addCell(v.getClientes() != null ? v.getClientes().getNomeCliFor() : "AVULSO");
            table.addCell(data);
            table.addCell(nf.format(v.getTotal_venda()));
            table.addCell(v.getObservacoes() != null ? v.getObservacoes() : "");
        }

        // Total
        PdfPCell cellTotal = new PdfPCell(new Phrase("TOTAL GERAL: " + nf.format(total)));
        cellTotal.setColspan(5);
        cellTotal.setHorizontalAlignment(Element.ALIGN_RIGHT);
        cellTotal.setBackgroundColor(new com.itextpdf.text.BaseColor(200, 200, 255));
        table.addCell(cellTotal);

        doc.add(table);
        doc.close();

        Desktop.getDesktop().open(new File(caminho));
    }

    private void gerarRelatorioLucro(ResultSet rs, LocalDate inicio, LocalDate fim) throws Exception {
        String caminho = System.getProperty("user.home") + "/Desktop/Lucro_"
                + inicio.format(DateTimeFormatter.ofPattern("dd-MM")) + "_a_"
                + fim.format(DateTimeFormatter.ofPattern("dd-MM-yyyy")) + ".pdf";

        Document doc = new Document();
        PdfWriter.getInstance(doc, new FileOutputStream(caminho));
        doc.open();

        doc.add(new Paragraph("APURAÇÃO DE LUCRO",
                FontFactory.getFont(FontFactory.HELVETICA_BOLD, 16)));
        doc.add(new Paragraph("Período: " + inicio.format(DateTimeFormatter.ofPattern("dd-MM-yyyy")) + " a " + fim.format(DateTimeFormatter.ofPattern("dd-MM-yyyy"))));
        doc.add(new Paragraph("Gerado em: " + LocalDateTime.now().format(
                DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm"))));
        doc.add(new Paragraph(" "));

        PdfPTable table = new PdfPTable(4);
        table.setWidthPercentage(100);
        table.addCell("Data");
        table.addCell("Faturado");
        table.addCell("Custo");
        table.addCell("Lucro");

        NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));
        double totalFaturado = 0, totalCusto = 0, totalLucro = 0;

        while (rs.next()) {
            String data = rs.getDate("data").toLocalDate()
                    .format(DateTimeFormatter.ofPattern("dd/MM/yyyy"));
            double faturado = rs.getDouble("faturado");
            double custo = rs.getDouble("custo");
            double lucro = rs.getDouble("lucro");

            totalFaturado += faturado;
            totalCusto += custo;
            totalLucro += lucro;

            table.addCell(data);
            table.addCell(nf.format(faturado));
            table.addCell(nf.format(custo));
            table.addCell(nf.format(lucro));
        }

        // Total
        table.addCell("TOTAL");
        table.addCell(nf.format(totalFaturado));
        table.addCell(nf.format(totalCusto));
        table.addCell(nf.format(totalLucro));

        doc.add(table);
        doc.close();

        Desktop.getDesktop().open(new File(caminho));
    }

