    private void btnPesquisarVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarVendaActionPerformed
        try {
            LocalDate inicio = LocalDate.parse(txtInicio.getText().trim(),
                    DateTimeFormatter.ofPattern("dd/MM/yyyy"));
            LocalDate fim = LocalDate.parse(txtFim.getText().trim(),
                    DateTimeFormatter.ofPattern("dd/MM/yyyy"));

            List<Vendas> lista = new VendasDAO().historicoVendas(inicio, fim);

            DefaultTableModel model = (DefaultTableModel) tabela.getModel();
            model.setRowCount(0);

            NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));
            double acumulado = 0.0;

            for (Vendas v : lista) {
                acumulado += v.getTotal_venda();

                // Formata a data do Timestamp
                String dataFormatada = v.getData_venda() != null
                        ? v.getData_venda().toLocalDateTime()
                                .format(DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm")) : "";

                model.addRow(new Object[]{
                    v.getId(),
                    v.getClientes() != null ? v.getClientes().getNomeCliFor() : "AVULSO",
                    dataFormatada,
                    nf.format(v.getTotal_venda()),
                    nf.format(acumulado),
                    v.getObservacoes() != null ? v.getObservacoes() : ""
                });
            }

            tabela.setDefaultRenderer(Object.class, new CustomTableCellRendererFat());

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btnPesquisarVendaActionPerformed

