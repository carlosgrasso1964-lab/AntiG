    private void jButtonImportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonImportarActionPerformed
        String user = "root";
        String pass = "";
        String nomedopc = null;
        try {
            nomedopc = InetAddress.getLocalHost().getHostName();
            System.out.println("nomedopc");
        } catch (UnknownHostException ex) {
            Logger.getLogger(Importar.class.getName()).log(Level.SEVERE, null, ex);
        }
        String escolha;
        if(nomedopc == "CARLOS_PCW"){
           //escolha = "C:\\wamp64\\bin\\mariadb\\mariadb11.3.2\\bin\\";
           escolha = "C:\\wamp64\\bin\\mysql\\mysql8.3.0\\bin\\";
        }else{
           escolha = "C:/Program Files/MySQL/MySQL Workbench 8.0 CE/mysql.exe";
        }
        //String[] restoreCmd = new String[]{"C:/Program Files/MySQL/MySQL Server 8.0/bin/mysql.exe","--user="+user,"--password="+pass,"-e","source " +path};
        //String[] restoreCmd = new String[]{"C:/Program Files/MySQL/MySQL Workbench 8.0 CE/mysql.exe","--user="+user,"--password="+pass,"-e","source " +path};   
        String[] restoreCmd = new String[]{escolha,"--user="+user,"--password="+pass,"-e","source " + path};
        try {
            Process process = Runtime.getRuntime().exec(restoreCmd);
            int procCom = 0;
            try {
                procCom = process.waitFor();
            } catch (InterruptedException ex) {
                Logger.getLogger(Importar.class.getName()).log(Level.SEVERE, null, ex);
            }
            if (procCom==0) {
               jLabel2.setText("Restaurado com Sucesso!!!");
            }else {
               jLabel2.setText("Restauração não realizada!"); 
            }
        } catch (IOException ex) {
            Logger.getLogger(Importar.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButtonImportarActionPerformed

