    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        try {
            LocalDate data = LocalDate.parse(txtData.getText().trim(),
                    java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy"));

            VendasDAO dao = new VendasDAO();
            double totalDoDia = dao.posicaoDoDia(data);

            NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));
            txtTotal.setText(nf.format(totalDoDia));

            // Mensagem bonita
            JOptionPane.showMessageDialog(this,
                    "<html><h2>VENDAS DO DIA " + txtData.getText() + "</h2>"
                    + "<h1 style='color:green;'>" + nf.format(totalDoDia) + "</h1></html>",
                    "Total do Dia", JOptionPane.INFORMATION_MESSAGE);

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Data inválida! Use o formato: dd/MM/yyyy", "Erro", JOptionPane.ERROR_MESSAGE);
            txtData.requestFocus();
            txtData.selectAll();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao consultar vendas:\n" + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnPesquisarActionPerformed

