    public void carregarDados() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"ID", "Descrição", "Qtd", "Preço Unit.", "Subtotal"}, 0
        );

        NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));

        for (ItensVendas item : itensVendas) {
            model.addRow(new Object[]{
                item.getProdutos().getId(),
                item.getProdutos().getDescricao(),
                String.format("%.3f", item.getQtd()),
                nf.format(item.getProdutos().getPrecoVenda()), // ? CORRIGIDO AQUI!
                nf.format(item.getSubtotal())
            });
        }

        // Se você tiver uma jTable chamada tabelaItens no Form_Pagamentos:
        tabelaItens.setModel(model);  // ? descomente se tiver

        // Total da venda
        txtTotalVenda.setText(nf.format(totalVenda));
    }


