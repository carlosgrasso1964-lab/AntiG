    private void btnPagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagarActionPerformed
        try {
            double dinheiro = parseMoeda(txtDinheiro.getText());
            double cartao = parseMoeda(txtCartao.getText());
            double cheque = parseMoeda(txtCheque.getText());
            double pix = parseMoeda(txtPix.getText());
            double totalPago = dinheiro + cartao + cheque + pix;

            if (totalPago < totalVenda) {
                JOptionPane.showMessageDialog(this, "Valor pago insuficiente!", "Erro", JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (JOptionPane.showConfirmDialog(this,
                    "Confirmar venda de R$ " + String.format("%,.2f", totalVenda)
                    + "\nTroco: R$ " + String.format("%,.2f", totalPago - totalVenda),
                    "Finalizar?", JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
                return;
            }

            try (Connection con = Conexao.faz_conexao()) {
                con.setAutoCommit(false);

                Vendas v = new Vendas();
                v.setClientes(clientes != null ? clientes : new CliFor()); // ? avulso se null
                v.setData_venda(java.sql.Timestamp.valueOf(java.time.LocalDateTime.now()));
                v.setTotal_venda(totalVenda);
                v.setObservacoes(txtObservacoes.getText().isEmpty() ? "Venda PDV" : txtObservacoes.getText());

                VendasDAO daoVenda = new VendasDAO();
                daoVenda.salvar(v, con); // ID já é setado dentro do método

                ItensVendasDAO itemDao = new ItensVendasDAO();
                ProdutosDAO prodDao = new ProdutosDAO();

//                for (ItensVendas item : itensVendas) {
//                    item.getVendas().setId(v.getId());
//                    itemDao.salvar(item, con);
//                    prodDao.baixaEstoque(item.getProdutos().getId(), item.getQtd(), con);
//                }
                for (ItensVendas item : itensVendas) {
                    // ASSOCIA O OBJETO VENDA AO ITEM ANTES DE SALVAR!
                    item.setVendas(v);  // ? ESSA LINHA É OBRIGATÓRIA!

                    itemDao.salvar(item, con);
                    prodDao.baixaEstoque(item.getProdutos().getId(), item.getQtd(), con);
                }

                con.commit();

                JOptionPane.showMessageDialog(this,
                        "VENDA Nº " + v.getId() + " FINALIZADA COM SUCESSO!\n"
                        + "Troco: R$ " + String.format("%,.2f", totalPago - totalVenda),
                        "SUCESSO!", JOptionPane.INFORMATION_MESSAGE);

                vendaFinalizada = true;
                dispose();

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "ERRO: " + e.getMessage());
                e.printStackTrace();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btnPagarActionPerformed

    // Método para limpar e converter o valor
    private double limparEConverterValor(String valor) {

        // Limpar espaços em branco
        String valorLimpo = valor.trim();

        // Se a string estiver vazia, retornar 0.0
        if (valorLimpo.isEmpty()) {
            return 0.0;
        }

        // Substituir a vírgula por ponto para o separador decimal
        valorLimpo = valorLimpo.replace(",", ".");

        // Remover pontos que estão antes da última vírgula (se houver)
        if (valorLimpo.indexOf('.') != valorLimpo.lastIndexOf('.')) {
            int lastPointIndex = valorLimpo.lastIndexOf('.');
            valorLimpo = valorLimpo.substring(0, lastPointIndex).replace(".", "") + valorLimpo.substring(lastPointIndex);
        }

        // Debug: imprime o valor limpo
        // System.out.println("Valor limpo após ajuste: " + valorLimpo);
        try {
            // Converter para double
            return Double.parseDouble(valorLimpo);
        } catch (NumberFormatException e) {
            // Se ocorrer um erro na conversão, imprimir mensagem de erro e retornar 0.0
            System.err.println("Erro ao converter valor: " + valor + ". " + e.getMessage());
            return 0.0;
        }
    }

    public String formatarQuantidade(double quantidade) {
        NumberFormat formatador = NumberFormat.getInstance();
        formatador.setMaximumFractionDigits(3); // Permite até 3 casas decimais
        formatador.setGroupingUsed(true); // Usar separadores de milhar
        return formatador.format(quantidade);
    }

    private double parseMoeda(String texto) {
        if (texto == null || texto.trim().isEmpty()) {
            return 0.0;
        }

        // Remove tudo que não for número, vírgula ou ponto
        String limpo = texto.replaceAll("[^0-9,\\.]", "");

        // Troca vírgula por ponto (padrão Brasil ? Java)
        limpo = limpo.replace(",", ".");

        try {
            return Double.parseDouble(limpo);
        } catch (NumberFormatException e) {
            System.out.println("Erro ao converter moeda: " + texto + " ? " + limpo);
            return 0.0;
        }
    }

