    public void gerarCupomPDF() {
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Salvar Cupom Não Fiscal");
        fileChooser.setFileFilter(new FileNameExtensionFilter("PDF Files", "pdf"));
        int userSelection = fileChooser.showSaveDialog(null);

        if (userSelection == JFileChooser.APPROVE_OPTION) {
            String file_name = fileChooser.getSelectedFile().getAbsolutePath();
            if (!file_name.toLowerCase().endsWith(".pdf")) {
                file_name += ".pdf";
            }

            Document document = new Document(PageSize.A4);
            document.setMargins(10f, 10f, 10f, 10f);

            try {
                PdfWriter.getInstance(document, new FileOutputStream(file_name));
                document.open();

                // Cabeçalho do cupom (igual antes)
                document.add(new Paragraph("********************************"));
                document.add(new Paragraph(" Cupom Não Fiscal ", FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12)));
                document.add(new Paragraph("********************************"));
                document.add(new Paragraph("ID Venda: " + txtIdVenda.getText()));
                document.add(new Paragraph("Total : " + txtTotalVenda.getText()));
                document.add(new Paragraph("Cliente : " + txtCliente.getText()));
                document.add(new Paragraph("Data : " + txtDataVenda.getText()));
                document.add(new Paragraph("Obs. : " + txtObs.getText()));
                document.add(new Paragraph("\nItens da Venda:"));
                document.add(new Paragraph("--------------------------------------------------------------------------------------------------------------------------------"));

                // Tabela com 6 colunas (sem custo médio pro cliente)
                PdfPTable tabela = new PdfPTable(6);
                tabela.setWidthPercentage(75);
                tabela.setWidths(new float[]{2f, 5f, 2f, 3f, 4f, 5f});

                // Cabeçalho
                tabela.addCell(getCell("Cod", PdfPCell.ALIGN_LEFT));
                tabela.addCell(getCell("Produto", PdfPCell.ALIGN_LEFT));
                tabela.addCell(getCell("Qtd", PdfPCell.ALIGN_CENTER));
                tabela.addCell(getCell("Preço", PdfPCell.ALIGN_RIGHT));
                tabela.addCell(getCell("Subtotal", PdfPCell.ALIGN_RIGHT));
                tabela.addCell(getCell("Acumulado", PdfPCell.ALIGN_RIGHT));

                DefaultTableModel model = (DefaultTableModel) Carrinho.getModel();
                double acumulado = 0.0;
                NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));

                for (int row = 0; row < model.getRowCount(); row++) {
                    // Colunas normais (já formatadas bonitinhas)
                    tabela.addCell(getCell(model.getValueAt(row, 0).toString(), PdfPCell.ALIGN_LEFT));     // Código
                    tabela.addCell(getCell(model.getValueAt(row, 1).toString(), PdfPCell.ALIGN_LEFT));     // Produto
                    tabela.addCell(getCell(model.getValueAt(row, 2).toString(), PdfPCell.ALIGN_CENTER));   // Qtd
                    tabela.addCell(getCell(model.getValueAt(row, 3).toString(), PdfPCell.ALIGN_RIGHT));    // Preço Unit.
                    tabela.addCell(getCell(model.getValueAt(row, 4).toString(), PdfPCell.ALIGN_RIGHT));    // Subtotal

                    // === CÁLCULO SEGURO DO ACUMULADO ===
                    String subtotalStr = model.getValueAt(row, 4).toString(); // ex: "R$ 71,76"
                    double subtotal = parseCurrencyToDouble(subtotalStr);
                    acumulado += subtotal;

                    // Mostra o acumulado já formatado com R$
                    tabela.addCell(getCell(nf.format(acumulado), PdfPCell.ALIGN_RIGHT));
                }

                document.add(tabela);
                document.add(new Paragraph("========================================================================="));

                JOptionPane.showMessageDialog(null, "PDF gerado com sucesso: " + file_name);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Erro ao gerar PDF: " + e.getMessage());
                e.printStackTrace();
            } finally {
                document.close();
            }
        }
    }

    // === FUNÇÃO MÁGICA QUE RESOLVE O PROBLEMA DA MOEDA BRASILEIRA ===
    private double parseCurrencyToDouble(String valor) {
        if (valor == null || valor.trim().isEmpty()) {
            return 0.0;
        }

        String limpo = valor
                .replace("R$", "")
                .replace(" ", "")
                .replace(" ", "") // esse espaço invisível maldito!
                .replace(".", "")
                .replace(",", ".")
                .trim();

        try {
            return Double.parseDouble(limpo);
        } catch (Exception e) {
            System.out.println("Erro ao converter: " + valor);
            return 0.0;
        }
    }

    // Função auxiliar para criar células sem borda
    private PdfPCell getCell(String text, int alignment) {
        PdfPCell cell = new PdfPCell(new Phrase(text));
        cell.setPadding(5);
        cell.setHorizontalAlignment(alignment);
        cell.setBorder(PdfPCell.NO_BORDER);
        return cell;
    }


