    private void carregarDadosVenda(int idVenda) {
        try {
            VendasDAO dao = new VendasDAO();
            Vendas v = dao.buscarPorId(idVenda);
            if (v != null) {
                txtIdVenda.setText(String.valueOf(v.getId()));
                txtCliente.setText(v.getClientes().getNomeCliFor());
                txtDataVenda.setText(v.getData_venda().toLocalDateTime()
                        .format(java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm")));
                txtTotalVenda.setText(NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"))
                        .format(v.getTotal_venda()));
                txtObs.setText(v.getObservacoes());

                // Carrega itens
                ItensVendasDAO itensDao = new ItensVendasDAO();
                List<ItensVendas> itens = itensDao.listarPorVenda(idVenda);
                DefaultTableModel model = (DefaultTableModel) Carrinho.getModel();
                model.setRowCount(0);

                NumberFormat nf = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"));
                double acumulado = 0.0;

                for (ItensVendas i : itens) {
                    acumulado += i.getSubtotal();

                    model.addRow(new Object[]{
                        i.getProdutos().getId(),
                        i.getProdutos().getDescricao(),
                        String.format("%.3f", i.getQtd()),
                        nf.format(i.getPrecoVenda()), // Preço unitário da época
                        nf.format(i.getSubtotal()), // Subtotal do item
                        nf.format(acumulado), // ? ACUMULADO (pro cliente no PDF)
                        nf.format(i.getPrecoMedioCusto()) // ? CUSTO MÉDIO (só pra você na tela!)
                    });
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar venda: " + e.getMessage());
            e.printStackTrace();
        }
    }

