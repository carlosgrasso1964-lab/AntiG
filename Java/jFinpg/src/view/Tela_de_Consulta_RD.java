    private void jButtonPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPesquisarActionPerformed

        if (jFormattedTextFieldDataIni.getText().trim().length() <= 4) {
            JOptionPane.showMessageDialog(null, "Atenção! Favor preencher o campo de data inicial corretamente.");
            return;
        }
        if (jFormattedTextFieldDataFim.getText().trim().length() <= 4) {
            JOptionPane.showMessageDialog(null, "Atenção! Favor preencher o campo de data final corretamente.");
            return;
        }

        // Variáveis para totais do período
        double receitasOperacionais = 0.0;
        double receitasNaoOperacionais = 0.0;
        double despesasOperacionais = 0.0;
        double despesasNaoOperacionais = 0.0;
        double totalReceitas = 0.0;
        double totalDespesas = 0.0;

        SimpleDateFormat formatoEntrada = new SimpleDateFormat("dd/MM/yyyy");
        formatoEntrada.setLenient(false);

        java.util.Date dataIniUtil;
        java.util.Date dataFimUtil;
        try {
            dataIniUtil = formatoEntrada.parse(jFormattedTextFieldDataIni.getText().trim());
            dataFimUtil = formatoEntrada.parse(jFormattedTextFieldDataFim.getText().trim());
        } catch (ParseException ex) {
            JOptionPane.showMessageDialog(null, "Formato de data inválido (use dd/MM/yyyy)");
            Logger.getLogger(Tela_de_Consulta_RD.class.getName()).log(Level.SEVERE, null, ex);
            return;
        }

        // Determina o campo de data
        String campoData;
        if (rbVcto.isSelected()) {
            campoData = "dtvcto";
        } else if (rbCompetencia.isSelected()) {
            campoData = "dtemi";
        } else {
            campoData = "dtapr";
        }

        // ???????????????????????????????????????????????
        // 1. Totais do período atual (para percentuais)
        // ???????????????????????????????????????????????
        try (Connection conTot = Conexao.faz_conexao(); PreparedStatement stmtTot = conTot.prepareStatement(
                "SELECT nome_s, SUM(valor) AS total "
                + "FROM viewmovrd "
                + "WHERE " + campoData + " BETWEEN ? AND ? "
                + "  AND nome_p <> 'NULO' "
                + "  AND classif NOT IN ('3.003.005', '4.008.011') "
                + "GROUP BY nome_s"
        )) {

            stmtTot.setDate(1, new java.sql.Date(dataIniUtil.getTime()));
            stmtTot.setDate(2, new java.sql.Date(dataFimUtil.getTime()));

            try (ResultSet rsTot = stmtTot.executeQuery()) {
                while (rsTot.next()) {
                    String nomeS = rsTot.getString("nome_s");
                    double valor = rsTot.getDouble("total");

                    if ("RECEITAS OPERACIONAIS".equalsIgnoreCase(nomeS)) {
                        receitasOperacionais += valor;
                        totalReceitas += valor;
                    } else if ("RECEITAS NÃO OPERACIONAIS".equalsIgnoreCase(nomeS)
                            || "RECEITAS NAO OPERACIONAIS".equalsIgnoreCase(nomeS)) {
                        receitasNaoOperacionais += valor;
                        totalReceitas += valor;
                    } else if ("DESPESAS OPERACIONAIS".equalsIgnoreCase(nomeS)) {
                        despesasOperacionais += valor;
                        totalDespesas += valor;
                    } else if ("DESPESAS NÃO OPERACIONAIS".equalsIgnoreCase(nomeS)
                            || "DESPESAS NAO OPERACIONAIS".equalsIgnoreCase(nomeS)) {
                        despesasNaoOperacionais += valor;
                        totalDespesas += valor;
                    }
                }
            }
        } catch (SQLException e) {
            Logger.getLogger(Tela_de_Consulta_RD.class.getName()).log(Level.SEVERE, "Erro ao obter totais do período", e);
            JOptionPane.showMessageDialog(null, "Erro ao consultar totais do período.");
            return;
        }

        // ???????????????????????????????????????????????
        // 2. Percentuais históricos (últimos 24 meses)
        // ???????????????????????????????????????????????
        Map<String, Double> mediaHistoricaPorConta = new HashMap<>();
        try (Connection conHist = Conexao.faz_conexao()) {

            LocalDate dataFim = dataFimUtil.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
            LocalDate dataIniHist = dataFim.minusMonths(24);
            Date sqlDataIniHist = Date.valueOf(dataIniHist);

            // Totais históricos gerais
            double totalRecHist = 0.0;
            double totalDespHist = 0.0;

            try (PreparedStatement stmtTotHist = conHist.prepareStatement(
                    "SELECT nome_s, SUM(valor) AS total "
                    + "FROM viewmovrd "
                    + "WHERE nome_p <> 'NULO' "
                    + "  AND " + campoData + " >= ? "
                    + "GROUP BY nome_s")) {

                stmtTotHist.setDate(1, sqlDataIniHist);
                try (ResultSet rs = stmtTotHist.executeQuery()) {
                    while (rs.next()) {
                        String nomeS = rs.getString("nome_s");
                        double tot = rs.getDouble("total");
                        if (nomeS != null) {
                            if (nomeS.toUpperCase().contains("RECEITAS")) {
                                totalRecHist += tot;
                            } else if (nomeS.toUpperCase().contains("DESPESAS")) {
                                totalDespHist += tot;
                            }
                        }
                    }
                }
            }

            // Média histórica por conta
            try (PreparedStatement stmtHist = conHist.prepareStatement(
                    "SELECT nome_c, nome_s, SUM(valor) AS total "
                    + "FROM viewmovrd "
                    + "WHERE nome_p <> 'NULO' "
                    + "  AND " + campoData + " >= ? "
                    + "GROUP BY nome_c, nome_s")) {

                stmtHist.setDate(1, sqlDataIniHist);
                try (ResultSet rsHist = stmtHist.executeQuery()) {
                    while (rsHist.next()) {
                        String nomeC = rsHist.getString("nome_c");
                        double totalConta = rsHist.getDouble("total");
                        double percHist = 0.0;

                        if (totalConta > 0 && totalRecHist != 0) {
                            percHist = (totalConta / totalRecHist) * 100;
                        } else if (totalConta < 0 && totalDespHist != 0) {
                            percHist = (totalConta / totalDespHist) * 100;
                        }

                        mediaHistoricaPorConta.put(nomeC, percHist);
                    }
                }
            }
        } catch (SQLException e) {
            Logger.getLogger(Tela_de_Consulta_RD.class.getName()).log(Level.SEVERE, "Erro ao consultar histórico 24 meses", e);
            // Aqui você pode decidir se continua ou retorna
            // Por enquanto continua, mas com histórico zerado
        }

        // ???????????????????????????????????????????????
        // 3. Consulta principal + preenchimento da tabela
        // ???????????????????????????????????????????????
        try (Connection con = Conexao.faz_conexao(); PreparedStatement stmt = con.prepareStatement(
                "SELECT nome_p, nome_s, nome_c, SUM(valor) AS total "
                + "FROM viewmovrd "
                + "WHERE " + campoData + " BETWEEN ? AND ? "
                + "  AND nome_p <> 'NULO' "
                + "  AND classif NOT IN ('3.003.005','4.008.011') "
                + "GROUP BY nome_p, nome_s, nome_c, classif "
                + "ORDER BY classif"
        )) {

            stmt.setDate(1, new java.sql.Date(dataIniUtil.getTime()));
            stmt.setDate(2, new java.sql.Date(dataFimUtil.getTime()));

            DefaultTableModel modelo = new DefaultTableModel(
                    new Object[]{"PRINCIPAL", "GRUPO", "CONTA", "TOTAL", "ACUMULADO", "PERCENTUAL", "MÉDIA HISTÓRICA (%)"},
                    0
            );
            jTablePesquisa.setModel(modelo);

            try (ResultSet rs = stmt.executeQuery()) {

                jTablePesquisa.setAutoResizeMode(JTable.AUTO_RESIZE_OFF);
                jTablePesquisa.getColumnModel().getColumn(0).setPreferredWidth(100);
                jTablePesquisa.getColumnModel().getColumn(1).setPreferredWidth(250);
                jTablePesquisa.getColumnModel().getColumn(2).setPreferredWidth(370);
                jTablePesquisa.getColumnModel().getColumn(3).setPreferredWidth(130);
                jTablePesquisa.getColumnModel().getColumn(4).setPreferredWidth(100);
                jTablePesquisa.getColumnModel().getColumn(5).setPreferredWidth(100);
                jTablePesquisa.getColumnModel().getColumn(6).setPreferredWidth(140);

                DefaultTableCellRenderer rightAlign = new DefaultTableCellRenderer();
                rightAlign.setHorizontalAlignment(SwingConstants.RIGHT);

                jTablePesquisa.getColumnModel().getColumn(3).setCellRenderer(rightAlign);
                jTablePesquisa.getColumnModel().getColumn(4).setCellRenderer(rightAlign);

                DecimalFormat df = new DecimalFormat("#,##0.00");
                DecimalFormat dp = new DecimalFormat("0.0000");

                double acumulado = 0.0;
                String ultimoPrin = "";
                String prin = "";
                String grupo = "";

                while (rs.next()) {
                    String nomeP = rs.getString("nome_p");
                    String nomeS = rs.getString("nome_s");
                    String nomeC = rs.getString("nome_c");
                    double valor = rs.getDouble("total");

                    double percentual = 0.0;
                    if (valor > 0 && totalReceitas != 0) {
                        percentual = (valor / totalReceitas) * 100;
                    } else if (valor < 0 && totalDespesas != 0) {
                        percentual = (valor / totalDespesas) * 100;
                    }

                    acumulado += valor;

                    // Linha separadora entre grupos PRINCIPAL
                    if (!ultimoPrin.isEmpty() && !ultimoPrin.equals(nomeP)) {
                        modelo.addRow(new Object[]{"", "", "", "", "", "", ""});
                    }

                    prin = prin.equals(nomeP) ? " " : nomeP;
                    grupo = grupo.equals(nomeS) ? " " : nomeS;

                    double histPerc = mediaHistoricaPorConta.getOrDefault(nomeC, 0.0);

                    modelo.addRow(new Object[]{
                        prin,
                        grupo,
                        nomeC,
                        df.format(valor),
                        df.format(acumulado),
                        dp.format(percentual),
                        dp.format(histPerc)
                    });

                    ultimoPrin = nomeP;
                    prin = nomeP;
                    grupo = nomeS;
                }

                // Linhas de resumo (igual à sua lógica original + MySQL)
                modelo.addRow(new Object[]{"", "", "", "", "", "", ""});
                String taxa = totalReceitas != 0 ? dp.format((-totalDespesas / totalReceitas) * 100) : "?";
                modelo.addRow(new Object[]{"", "", "TAXA DE CONSUMO", "", "", taxa, ""});

                long diasPeriodo = ChronoUnit.DAYS.between(
                        dataIniUtil.toInstant().atZone(ZoneId.systemDefault()).toLocalDate(),
                        dataFimUtil.toInstant().atZone(ZoneId.systemDefault()).toLocalDate()
                ) + 1;

                double recDiaria = totalReceitas != 0 ? totalReceitas / diasPeriodo : 0.0;
                int diasReceita = (int) Math.round(recDiaria);
                double diasConsumidos = recDiaria != 0 ? totalDespesas / recDiaria : 0.0;
                int diasDespesa = (int) Math.round(diasConsumidos);

                modelo.addRow(new Object[]{"", "", "", "", "", "", ""});
                modelo.addRow(new Object[]{"", "", "TOTAL DIAS NO PERÍODO: " + diasPeriodo + " dias", "", "", "", ""});
                modelo.addRow(new Object[]{"", "", "DIAS EQUIVALENTES CONSUMIDOS: " + (-diasDespesa) + " dias", "", "", "", ""});

                // Resumo final das categorias
                modelo.addRow(new Object[]{"", "", "", "", "", "", ""});
                modelo.addRow(new Object[]{"", "", "RECEITAS OPERACIONAIS", "", df.format(receitasOperacionais), "", ""});
                modelo.addRow(new Object[]{"", "", "DESPESAS OPERACIONAIS", "", df.format(despesasOperacionais), "", ""});
                modelo.addRow(new Object[]{"", "", "RESULTADO OPERACIONAL", "", df.format(receitasOperacionais + despesasOperacionais), "", ""});

                modelo.addRow(new Object[]{"", "", "", "", "", "", ""});
                modelo.addRow(new Object[]{"", "", "RECEITAS NÃO OPERACIONAIS", "", df.format(receitasNaoOperacionais), "", ""});
                modelo.addRow(new Object[]{"", "", "DESPESAS NÃO OPERACIONAIS", "", df.format(despesasNaoOperacionais), "", ""});
                modelo.addRow(new Object[]{"", "", "RESULTADO NÃO OPERACIONAL", "", df.format(receitasNaoOperacionais + despesasNaoOperacionais), "", ""});

                modelo.addRow(new Object[]{"", "", "", "", "", "", ""});
                modelo.addRow(new Object[]{"", "", "RESULTADO FINAL DO PERÍODO:", "",
                    df.format(receitasOperacionais + despesasOperacionais + receitasNaoOperacionais + despesasNaoOperacionais),
                    "", ""});

                // Renderers personalizados
                jTablePesquisa.getColumnModel().getColumn(3).setCellRenderer(new CustomTableCellRenderer(3, 11, false));
                jTablePesquisa.getColumnModel().getColumn(4).setCellRenderer(new CustomTableCellRenderer(4, 11, false));

                PercentualRenderer percRenderer = new PercentualRenderer();
                jTablePesquisa.getColumnModel().getColumn(5).setCellRenderer(percRenderer);
                jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(percRenderer);
            }

        } catch (SQLException e) {
            Logger.getLogger(Tela_de_Consulta_RD.class.getName()).log(Level.SEVERE, "Erro na consulta principal", e);
            JOptionPane.showMessageDialog(null, "Erro ao carregar dados da consulta.");
        }
    }//GEN-LAST:event_jButtonPesquisarActionPerformed

