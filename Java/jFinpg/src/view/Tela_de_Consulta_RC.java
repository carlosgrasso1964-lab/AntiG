    private String formatarNegativo(double valor) {
        // === FORMATADOR DE MOEDA ===
        DecimalFormatSymbols symbols = new DecimalFormatSymbols();
        symbols.setDecimalSeparator(',');
        symbols.setGroupingSeparator('.');
        DecimalFormat dfCurrency = new DecimalFormat("#,##0.00", symbols);

        double valorExibir = (valor <= 0) ? valor : -valor;  // força negativo

        String formatado = dfCurrency.format(valorExibir);
        // Se quiser em vermelho (funciona com JTable + HTML)
        //return "<html><font color=" + (valorExibir < 0 ? "red" : "green") + ">" + formatado + "</font></html>";
        // Ou sem cor (só negativo):
        return dfCurrency.format(valorExibir);
    }

    // Só para deixar os empréstimos com sinal invertido na tela
    private String formatarEmprestimoVisual(double valor, boolean inverterSinal) {

        // === FORMATADOR DE MOEDA ===
        DecimalFormatSymbols symbols = new DecimalFormatSymbols();
        DecimalFormatSymbols br = new DecimalFormatSymbols(new Locale.Builder().setLanguage("pt").setRegion("BR").build());
        br.setDecimalSeparator(',');
        br.setGroupingSeparator('.');
        symbols.setDecimalSeparator(',');
        symbols.setGroupingSeparator('.');
        DecimalFormat dfCurrency = new DecimalFormat("#,##0.00", symbols);
        DecimalFormat dfNumero = new DecimalFormat("#,##0.00", br);
        double valorExibir = inverterSinal ? -valor : valor;
        return dfNumero.format(valorExibir);  // ? só retorna " -1.300,00 " ou " 700,00 "
    }


