    private void jButtonSalvaprevActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvaprevActionPerformed

        jRadioButtonPrev.setSelected(true);
        jButtonPesquisarActionPerformed(null);

        String inflacaoStr = JOptionPane.showInputDialog(this, "Expectativa de Inflação/Reajuste (%) considerada:");
        if (inflacaoStr == null) {
            return;
        }

        // 1. Primeiro, geramos o PDF como você já faz
        gerarPDFSnapshot(inflacaoStr);

        // 2. Agora, vamos salvar os dados na tb_plano_diretor
        double inflacao = Double.parseDouble(inflacaoStr.replace(",", "."));
        int anoAtual = java.util.Calendar.getInstance().get(java.util.Calendar.YEAR);
        
        
        Connection conn = null;
        PreparedStatement pst = null;

        try {
            
            try {
                // === ABRIR CONEXÃO ===
                conn = Conexao.faz_conexao();
                String sql = "INSERT INTO tb_plano_diretor (ano_referencia, mes, conta, valor_planejado, inflacao_premissa) VALUES (?, ?, ?, ?, ?)";
                pst = conn.prepareStatement(sql);

                for (int i = 0; i < jTablePesquisa.getRowCount(); i++) {
                    // Captura o nome da conta com segurança
                    Object objConta = jTablePesquisa.getValueAt(i, 0);
                    if (objConta == null) {
                        continue; // Pula se a linha estiver totalmente vazia
                    }
                    String nomeConta = objConta.toString();

                    // FILTRO DE SEGURANÇA: Só deixa passar o que não for Saldo/Resultado/Totais
                    if (nomeConta.startsWith("Saldo")
                            || nomeConta.startsWith("Resultado")
                            || nomeConta.startsWith("Receitas")
                            || nomeConta.startsWith("Despesas")) {
                        continue; // Pula para a próxima linha da tabela sem salvar essa
                    }

                    for (int mes = 1; mes <= 12; mes++) {
                        Object valorObj = jTablePesquisa.getValueAt(i, mes);

                        // Verifica se a célula não está nula antes de processar
                        if (valorObj != null && !valorObj.toString().trim().isEmpty()) {
                            String valorStr = valorObj.toString();

                            // Limpeza para evitar o erro de "multiple points"
                            valorStr = valorStr.replace(".", "").replace(",", ".");

                            try {
                                double valor = Double.parseDouble(valorStr);

                                if (valor != 0) {
                                    pst.setInt(1, anoAtual);
                                    pst.setInt(2, mes);
                                    pst.setString(3, nomeConta);
                                    pst.setDouble(4, valor);
                                    pst.setDouble(5, inflacao);
                                    pst.addBatch();
                                }
                            } catch (NumberFormatException nfe) {
                                // Ignora valores que não sejam números (ex: strings acidentais)
                                continue;
                            }
                        }
                    }
                }

                pst.executeBatch();
                JOptionPane.showMessageDialog(null, "Snapshot salvo com sucesso para análise da Lia!");

            } catch (Exception e) {
                e.printStackTrace(); // Mostra o erro detalhado no console do NetBeans
                JOptionPane.showMessageDialog(null, "Erro ao salvar no banco: " + e.getMessage());
            }

            pst.executeBatch(); // Executa tudo de uma vez
            JOptionPane.showMessageDialog(null, "Snapshot salvo com sucesso no banco de dados para análise da Lia!");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Erro ao salvar snapshot no banco: " + e.getMessage());
        } finally {
            // Fechar conexões (ajuste conforme seus métodos de fechar)
            try {
                if (conn != null) {
                    conn.close();
                }
                if (pst != null) {
                    pst.close();
                }
            } catch (Exception e) {
            }
        }
    }//GEN-LAST:event_jButtonSalvaprevActionPerformed

    private void gerarPDFSnapshot(String inflacao) {
        String dataHoraAtual = new SimpleDateFormat("yyyyMMdd_HHmmss").format(new Date());
        String nomeArquivo = "previsoes_" + dataHoraAtual + ".pdf";

        File dir = new File("snapshots");
        if (!dir.exists()) {
            dir.mkdirs();
        }
        String caminho = "snapshots/" + nomeArquivo;

        Document documento = new Document(PageSize.A4.rotate(), 30, 30, 40, 40);
        try {
            PdfWriter.getInstance(documento, new FileOutputStream(caminho));
            documento.open();

            com.itextpdf.text.Font tituloFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 16, BaseColor.BLACK);
            com.itextpdf.text.Font normalFont = FontFactory.getFont(FontFactory.HELVETICA, 10, BaseColor.BLACK);
            com.itextpdf.text.Font negritoFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, BaseColor.BLACK);

            documento.add(new Paragraph("SNAPSHOT DE PLANEJAMENTO - PREVISÕES", tituloFont));
            documento.add(new Paragraph("Data da Exportação: " + new SimpleDateFormat("dd/MM/yyyy HH:mm:ss").format(new Date()), normalFont));
            documento.add(new Paragraph("Expectativa de Inflação/Reajuste: " + inflacao + "%", normalFont));
            documento.add(new Paragraph(" ", normalFont));

            PdfPTable pdfTable = new PdfPTable(jTablePesquisa.getColumnCount());
            pdfTable.setWidthPercentage(100);

            for (int i = 0; i < jTablePesquisa.getColumnCount(); i++) {
                PdfPCell cell = new PdfPCell(new Phrase(jTablePesquisa.getColumnName(i), negritoFont));
                cell.setBackgroundColor(BaseColor.LIGHT_GRAY);
                cell.setHorizontalAlignment(Element.ALIGN_CENTER);
                pdfTable.addCell(cell);
            }

            for (int rows = 0; rows < jTablePesquisa.getRowCount(); rows++) {
                for (int cols = 0; cols < jTablePesquisa.getColumnCount(); cols++) {
                    Object val = jTablePesquisa.getModel().getValueAt(rows, cols);
                    String text = (val == null) ? "" : val.toString();
                    PdfPCell cell = new PdfPCell(new Phrase(text, normalFont));

                    if (cols > 0) {
                        cell.setHorizontalAlignment(Element.ALIGN_RIGHT);
                    }

                    pdfTable.addCell(cell);
                }
            }

            documento.add(pdfTable);
            documento.close();

            JOptionPane.showMessageDialog(this, "Snapshot salvo com sucesso:\n" + new File(caminho).getAbsolutePath());

            if (Desktop.isDesktopSupported()) {
                Desktop.getDesktop().open(new File(caminho));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao gerar PDF: " + e.getMessage());
            e.printStackTrace();
        }
    }

