    public class XYLineChart extends JFrame {

        JFreeChart chart;
        double[] receitasMensais;
        double[] despesasMensais;
        double[] resultadosMensais;

        public XYLineChart(double[] receitasMensais, double[] despesasMensais, double[] resultadosMensais) throws ParseException, SQLException {
            super("Gráfico de Resultados");
            setSize(800, 600);
            setLayout(null);
            setResizable(false);
            setLocationRelativeTo(null);
            setDefaultCloseOperation(DISPOSE_ON_CLOSE);

            this.receitasMensais = receitasMensais;
            this.despesasMensais = despesasMensais;
            this.resultadosMensais = resultadosMensais;

            crearGrafico();
            ChartPanel panel = new ChartPanel(chart, false);
            panel.setBounds(10, 20, 760, 520);
            add(panel);
            setVisible(true);
        }

        public void crearGrafico() throws ParseException, SQLException {
            XYSeries seriesReceitas = new XYSeries("Receitas");
            XYSeries seriesDespesas = new XYSeries("Despesas");
            XYSeries seriesResultados = new XYSeries("Resultados");
            XYSeries seriesSaldoFinal = new XYSeries("Saldo Final");

            DecimalFormatSymbols otherSymbols = new DecimalFormatSymbols(Locale.getDefault());
            otherSymbols.setDecimalSeparator('.');

            // Suponha que os meses sejam representados por números inteiros de 1 a 12
            for (int i = 0; i < 12; i++) {
                int mes = i + 1; // Adicionando 1 para representar os meses de 1 a 12
                // Adicionar o ponto (mês, valor formatado da receita) à série
                seriesReceitas.add(mes, receitasMensais[i]);
                seriesDespesas.add(mes, despesasMensais[i] * -1);
                seriesResultados.add(mes, resultadosMensais[i]);
                seriesSaldoFinal.add(mes, saldoFinalMensal[i]);
            }

            XYSeriesCollection dataset = new XYSeriesCollection();
            dataset.addSeries(seriesReceitas);
            dataset.addSeries(seriesDespesas);
            dataset.addSeries(seriesResultados);
            dataset.addSeries(seriesSaldoFinal);

            chart = ChartFactory.createXYLineChart(
                    "Receitas x Despesas x Resultado x Saldo Final",
                    "Meses",
                    "Valores",
                    dataset,
                    PlotOrientation.VERTICAL,
                    true, true, false
            );

            XYPlot plot = (XYPlot) chart.getPlot();
            XYLineAndShapeRenderer renderer = new XYLineAndShapeRenderer();

            // Define a cor das linhas
            renderer.setSeriesPaint(0, Color.BLUE); // Receitas
            renderer.setSeriesPaint(1, Color.RED);  // Despesas
            renderer.setSeriesPaint(2, Color.GREEN); // Resultados
            renderer.setSeriesPaint(3, new Color(255, 140, 0)); // Saldo Final (laranja)

            // Adiciona o gerador de dicas de ferramenta
            renderer.setBaseToolTipGenerator(new StandardXYToolTipGenerator(
                    StandardXYToolTipGenerator.DEFAULT_TOOL_TIP_FORMAT,
                    new DecimalFormat("0"), new DecimalFormat("0.00")));

            // Ajusta o renderer para o plot
            plot.setRenderer(renderer);

            // Ajusta o formato dos números no eixo vertical (valores)
            NumberAxis rangeAxis = (NumberAxis) plot.getRangeAxis();
            rangeAxis.setNumberFormatOverride(new DecimalFormat("#,##0.00"));
        }
    }

    public class ColorearTabla extends DefaultTableCellRenderer {

        private Component componente;

        @Override
        public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
            componente = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
            Font font = new Font("Tahoma", Font.PLAIN, 11);

            // Verifica se o valor é uma string vazia
            if (value != null && !value.toString().isEmpty()) {
                String confere = value.toString().replaceAll(",", "");
                Double muda = Double.valueOf(confere);
                if (muda >= 0) {
                    this.setForeground(Color.black);
                    this.setHorizontalAlignment(RIGHT);
                    componente.setFont(font);
                } else {
                    this.setForeground(Color.RED);
                    this.setHorizontalAlignment(RIGHT);
                }
            } else {
                // Se o valor for uma string vazia, mantenha a cor padrão e a formatação
                this.setForeground(table.getForeground());
                this.setHorizontalAlignment(RIGHT);
            }

            return this;
        }
    }
