    private void buscarProdutoPorCodigo() {
        try {
            int id = Integer.parseInt(txtCodigo.getText());
            ProdutosDAO dao = new ProdutosDAO();
            Produtos p = dao.buscarPorId(id);

            if (p != null && p.getId() != 0) {
                txtProduto.setText(p.getDescricao());
                txtPreco.setText(NumberFormat.getCurrencyInstance(Locale.of("pt", "BR")).format(p.getPrecoVenda()));
                txtEstoque.setText(String.format("%.3f", p.getQtd_estoque()));
                txtQtd.setText("1");
                txtQtd.requestFocus();
                txtQtd.selectAll();
            } else {
                JOptionPane.showMessageDialog(this, "Produto não encontrado!");
                txtCodigo.setText("");
                txtCodigo.requestFocus();
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Código inválido!");
        } catch (SQLException ex) {
            Logger.getLogger(Form_Vendas.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_txtCodigoKeyPressed

