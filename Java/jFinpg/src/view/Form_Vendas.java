    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        try {
            double qtd = Double.parseDouble(txtQtd.getText().replace(",", "."));
            double estoque = Double.parseDouble(txtEstoque.getText().replace(",", "."));
            double preco = NumberFormat.getCurrencyInstance(Locale.of("pt", "BR"))
                    .parse(txtPreco.getText()).doubleValue();

            if (qtd <= 0) {
                JOptionPane.showMessageDialog(this, "Quantidade deve ser maior que zero!");
                return;
            }
            if (qtd > estoque) {
                JOptionPane.showMessageDialog(this, "Quantidade maior que o estoque!");
                return;
            }

            double subtotal = preco * qtd;
            total += subtotal;

            int id = Integer.parseInt(txtCodigo.getText());

            meus_produtos.addRow(new Object[]{
                id,
                txtProduto.getText(),
                String.format("%.3f", qtd),
                txtPreco.getText(),
                NumberFormat.getCurrencyInstance(Locale.of("pt", "BR")).format(subtotal)
            });

            // Adiciona na lista de itens
            ItensVendas item = new ItensVendas();
            ProdutosDAO dao = new ProdutosDAO();
            Produtos produtoCompleto = dao.buscarPorIdComCusto(id);
            Produtos p = new Produtos();
            p.setId(id);
            p.setDescricao(txtProduto.getText());
            p.setPrecoVenda(preco);
            p.setPrecoMedioCusto(produtoCompleto.getPrecoMedioCusto()); // GRAVA O CUSTO NA VENDA!
            item.setProdutos(p);
            item.setQtd(qtd);
            item.setSubtotal(subtotal);
            item.setPrecoMedioCusto(produtoCompleto.getPrecoMedioCusto()); // AQUI GRAVA O CUSTO!
            itensVendas.add(item);
            txtTotalVenda.setText(NumberFormat.getCurrencyInstance(Locale.of("pt", "BR")).format(total));

            // Limpa campos do produto
            txtCodigo.setText("");
            txtProduto.setText("");
            txtPreco.setText("");
            txtEstoque.setText("");
            txtQtd.setText("1");
            txtCodigo.requestFocus();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao adicionar item: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAdicionarActionPerformed


