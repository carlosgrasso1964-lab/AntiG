    private String formatarCPF(String cpf) {
        try {
            MaskFormatter formatter = new MaskFormatter("###.###.###-##");
            formatter.setValueContainsLiteralCharacters(false);
            return formatter.valueToString(cpf.replaceAll("\\D", "")); // Remove caracteres não numéricos antes de formatar
        } catch (Exception e) {
            e.printStackTrace();
            return cpf; // Retorna o CPF sem formatação em caso de erro
        }
    }

    private double formatarMoedaParaDouble(String valor) {
        try {
            // Exibe o valor original para análise
            //System.out.println("Valor original antes de limpar: " + valor);

            // Remove o símbolo "R$", remove todos os tipos de espaço (incluindo espaços invisíveis), pontos e vírgulas
            String valorLimpo = valor.replace("R$", "").replace("\u00A0", "").trim().replace(".", "").replace(",", ".");

            // Exibe o valor limpo antes de converter
            //System.out.println("Valor limpo: " + valorLimpo);
            return Double.parseDouble(valorLimpo);
        } catch (NumberFormatException e) {
            System.out.println("Erro ao converter o valor: " + valor);
            return 0;
        }
    }

