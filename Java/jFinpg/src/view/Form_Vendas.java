    private static class CarregarCbx {

        @SuppressWarnings({"empty-statement", "unchecked", "unchecked"})
        public void CarregarCbx(String tabela, String valor, JComboBox combo) throws SQLException {
            String sql = "Select * FROM " + tabela + " WHERE tipo = 'CLI' ORDER BY nomeclifor";
            // Cria uma instância da classe Conexao
            Conexao conexao = new Conexao();
            try (Connection con = Conexao.faz_conexao(); PreparedStatement stmt = con.prepareStatement(sql); ResultSet rs = stmt.executeQuery()) {

                while (rs.next()) {
                    String nome = rs.getString("nomeclifor");
                    int id = rs.getInt("codclifor");
                    String Ncpf = rs.getString("cpf");
                    combo.addItem(nome + " | " + id + " | " + formatarCpfCnpj(Ncpf));
                }

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null,
                        "Erro ao carregar fornecedores:\n" + ex.getMessage(),
                        "Erro", JOptionPane.ERROR_MESSAGE);
                ex.printStackTrace();
            }

        }
    }

