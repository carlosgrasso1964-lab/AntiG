    private void cbxClientesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbxClientesActionPerformed
        Object itemSelecionado = cbxClientes.getSelectedItem();
        if (itemSelecionado == null || itemSelecionado.toString().trim().isEmpty()) {
            limparCamposCliente();
            clientes = null;
            return;
        }

        String texto = itemSelecionado.toString().trim();

        // ACEITA QUALQUER FORMATO COM | (com ou sem espaços)
        String[] partes = texto.split("\\s*\\|\\s*", 3);  // ? A MÁGICA!

        if (partes.length < 3) {
            System.out.println("Formato inválido no combo: " + texto);
            limparCamposCliente();
            clientes = null;
            return;
        }

        String nomeCliente = partes[0].trim();
        String idCliente = partes[1].trim();      // ? "1000"
        String documento = partes[2].trim();

        // Preenche os campos visuais
        jTextFieldid.setText(idCliente);
        txtCpf.setText(documento);

        // Preenche o objeto cliente
        clientes = new CliFor();
        clientes.setCodCliFor(idCliente);
        clientes.setNomeCliFor(nomeCliente);

        System.out.println("Cliente selecionado: " + nomeCliente + " | Código: " + idCliente);
    }

    private static String formatarCpfCnpj(String doc) {
        if (doc == null) {
            return "";
        }
        doc = doc.replaceAll("\\D", ""); // remove tudo que não é número

        if (doc.length() == 11) {
            return doc.replaceAll("(\\d{3})(\\d{3})(\\d{3})(\\d{2})", "$1.$2.$3-$4");
        } else if (doc.length() == 14) {
            return doc.replaceAll("(\\d{2})(\\d{3})(\\d{3})(\\d{4})(\\d{2})", "$1.$2.$3/$4-$5");
        }
        return doc; // retorna como está se não for CPF nem CNPJ
    }

