    @SuppressWarnings("unchecked")
    private void jButtonPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPesquisarActionPerformed
        try {
            DecimalFormat df = new DecimalFormat("#,##0.00");
            DecimalFormatSymbols symbols = new DecimalFormatSymbols();
            symbols.setDecimalSeparator(',');
            symbols.setGroupingSeparator('.');
            df.setDecimalFormatSymbols(symbols);

            Date dataSistema = new Date();
            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy - HH:mm:ss");
            jLabelDataH.setText(formato.format(dataSistema));

            Connection con = Conexao.faz_conexao();

            // 1. Consulta principal: todos os saldos da view
            String sql = "SELECT principal, subprincipal, conta, fonte, vrecurso, recurso, saldos "
                    + "FROM vsaldos "
                    + "ORDER BY "
                    + "CAST(SPLIT_PART(vrecurso, '.', 1) AS INTEGER), "
                    + "CAST(SPLIT_PART(vrecurso, '.', 2) AS INTEGER), "
                    + "CAST(SPLIT_PART(vrecurso, '.', 3) AS INTEGER)";
            PreparedStatement stmt = con.prepareStatement(sql);
            ResultSet rs = stmt.executeQuery();

            // 2. Consulta para pegar o saldo do Empréstimo Obtido (recurso 0080)
            String sqlEmprestimo = "SELECT COALESCE(SUM(saldos), 0) AS saldo_emprestimo "
                    + "FROM vsaldos "
                    + "WHERE recurso = '0080'";
            PreparedStatement stmtEmp = con.prepareStatement(sqlEmprestimo);
            ResultSet rsEmp = stmtEmp.executeQuery();
            double saldoEmprestimo = rsEmp.next() ? rsEmp.getDouble("saldo_emprestimo") : 0.0;

            // Configurar tabela
            DefaultTableModel modelo = (DefaultTableModel) jTablePesquisa.getModel();
            modelo.setNumRows(0);
            jTablePesquisa.setRowSorter(new TableRowSorter(modelo));
            jTablePesquisa.setAutoResizeMode(JTable.AUTO_RESIZE_OFF);

            // Tamanhos das colunas
            jTablePesquisa.getColumnModel().getColumn(0).setPreferredWidth(90);  // Principal
            jTablePesquisa.getColumnModel().getColumn(1).setPreferredWidth(180); // Sub
            jTablePesquisa.getColumnModel().getColumn(2).setPreferredWidth(240); // Conta
            jTablePesquisa.getColumnModel().getColumn(3).setPreferredWidth(300); // Fonte
            jTablePesquisa.getColumnModel().getColumn(4).setPreferredWidth(100); // vrecurso
            jTablePesquisa.getColumnModel().getColumn(5).setPreferredWidth(75);  // recurso
            jTablePesquisa.getColumnModel().getColumn(6).setPreferredWidth(100); // Saldo
            jTablePesquisa.getColumnModel().getColumn(7).setPreferredWidth(100); // Acumulado

            DefaultTableCellRenderer rightRenderer = new DefaultTableCellRenderer();
            rightRenderer.setHorizontalAlignment(SwingConstants.RIGHT);
            jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(rightRenderer);
            jTablePesquisa.getColumnModel().getColumn(7).setCellRenderer(rightRenderer);

            double acumulado = 0.0;
            String prin = "", sub = "", cta = "";

            while (rs.next()) {
                String recursoAtual = rs.getString("recurso");
                double saldoAtual = rs.getDouble("saldos");

//                // AJUSTE: Se for recurso 0079, subtrai o empréstimo
//                if ("0079".equals(recursoAtual)) {
//                    saldoAtual -= saldoEmprestimo;  // -1549.33 - (-600.00) = -949.33
//                }

                acumulado += saldoAtual;

                // Controle de exibição (esconde repetições)
                String novoPrin = prin.equals(rs.getString("principal")) ? "" : rs.getString("principal");
                String novoSub = sub.equals(rs.getString("subprincipal")) ? "" : rs.getString("subprincipal");
                String novaCta = cta.equals(rs.getString("conta")) ? "" : rs.getString("conta");

                if (!novaCta.isEmpty()) {
                    modelo.addRow(new Object[]{"", "", "", "", "", "", "", ""}); // linha em branco
                }

                modelo.addRow(new Object[]{
                    novoPrin,
                    novoSub,
                    novaCta,
                    rs.getString("fonte"),
                    rs.getString("vrecurso"),
                    recursoAtual,
                    df.format(saldoAtual),
                    df.format(acumulado)
                });

                prin = rs.getString("principal");
                sub = rs.getString("subprincipal");
                cta = rs.getString("conta");
            }

            // Adiciona linha de total de empréstimos (opcional)
            //modelo.addRow(new Object[]{"", "", "", "", "", "", "", ""});
            //modelo.addRow(new Object[]{"", "", "", "Empréstimos (saldo)", "", "0080", df.format(saldoEmprestimo), df.format(acumulado)});

            // Aplicar cores
            jTablePesquisa.getColumnModel().getColumn(6).setCellRenderer(new CustomTableCellRenderer(6, 11, false));

            // Fechar recursos
            rs.close();
            rsEmp.close();
            stmt.close();
            stmtEmp.close();
            con.close();

        } catch (SQLException ex) {
            Logger.getLogger(Tela_de_Consulta_Saldos.class.getName()).log(Level.SEVERE, null, ex);
            javax.swing.JOptionPane.showMessageDialog(null, "Erro ao consultar saldos: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonPesquisarActionPerformed

