// Método auxiliar para o salto das datas (incluindo o BIMESTRAL)
    private void avancarData(Calendar cal, String opc, int diaOriginal) {
        switch (opc) {
            case "1" ->
                cal.add(Calendar.MONTH, 1);
            case "2" ->
                cal.add(Calendar.MONTH, 3);
            case "3" ->
                cal.add(Calendar.MONTH, 2); // BIMESTRAL
            case "4" ->
                cal.add(Calendar.YEAR, 1);
            case "5" ->
                cal.add(Calendar.WEEK_OF_YEAR, 1);
            case "6" ->
                cal.add(Calendar.DAY_OF_YEAR, 1);
            case "7" ->
                cal.add(Calendar.MONTH, 4);
        }
        // Ajuste para não perder o dia 31 em meses que terminam em 30 ou 28
        int maxDia = cal.getActualMaximum(Calendar.DAY_OF_MONTH);
        cal.set(Calendar.DAY_OF_MONTH, Math.min(diaOriginal, maxDia));
    }


