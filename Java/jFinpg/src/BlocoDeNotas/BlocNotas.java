    private void AbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AbrirActionPerformed

        JFileChooser fc = new JFileChooser();

        fc.setMultiSelectionEnabled(false);
        fc.setFileSelectionMode(JFileChooser.FILES_ONLY);
        int seleccion = fc.showOpenDialog(this.getContentPane());

        // Si hemos pulsado en OK
        if (seleccion == JFileChooser.APPROVE_OPTION) {

            // Fichero seleccionado
            this.ficheroActual = fc.getSelectedFile();

            // Leemos el fichero
            try (FileReader fr = new FileReader(this.ficheroActual)) {
                String cadena = "";
                int valor = fr.read();
                while (valor != -1) {
                    cadena += (char) valor;
                    valor = fr.read();
                }
                // Ponemos el contenido del fichero en el textarea
                this.txtareaContenido.setText(cadena);

            } catch (FileNotFoundException ex) {
                System.out.println(ex.getMessage());
            } catch (IOException ex) {
                System.out.println(ex.getMessage());
            }

        }


    }//GEN-LAST:event_AbrirActionPerformed

    private void SalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SalvarActionPerformed

        // Sino tenemos un fichero actualmente, abrimos una ventana
        // Si lo tenemos, escribimos en el fichero actual
        if (this.ficheroActual == null) {

            this.abrirVentanaGuardar();

        } else {

            this.escribirFichero();
        }

    }//GEN-LAST:event_SalvarActionPerformed

