    private String sanitizeString(String input) {

        if (input == null) {

            return null;

        }

        // Remove todos os caracteres não numéricos, exceto a vírgula

        return input.replaceAll("[^\\d,]", "").replace(",", ".").trim();

    }



    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed

        Connection conn = null; // Declara a conexão

        try {

            conexao.abrirConexao(); // Abre a conexão

            conn = conexao.getConexao(); // Obtém a conexão

            // Leitura e conversão das quantidades

            String qtdAtualStr = txtQtdAtual.getText().trim();

            String qtdNovaStr = txtQtd_Nova.getText().trim();



            String estoqueMinimoStr = sanitizeString(txtEstoqueMinimo.getText());

            String estoqueMaximoStr = sanitizeString(txtEstoqueMaximo.getText());

            String precoAtualStr = sanitizeString(txtPrecoAtual.getText());

            String precoNovoStr = sanitizeString(txtPrecoNovo.getText());



            // Conversão para double

            double qtdAtual = Double.parseDouble(qtdAtualStr.replace(",", "."));

            double qtdNova = Double.parseDouble(qtdNovaStr.replace(",", "."));

            double estoqueMinimo = Double.parseDouble(estoqueMinimoStr);

            double estoqueMaximo = Double.parseDouble(estoqueMaximoStr);

            double precoAtual = Double.parseDouble(precoAtualStr.replace(".", "").replace(",", "."));

            double precoNovo = Double.parseDouble(precoNovoStr.replace(".", "").replace(",", "."));



            // Cálculo da quantidade atualizada

            double qtdAtualizada = qtdAtual + qtdNova;

            //double qtdAtualizada = qtdAtual + estoqueAtualizado;



            // Logs para depuração

//            System.out.println("Quantidade Atual: " + qtdAtual);

//            System.out.println("Quantidade Nova: " + qtdNova);

//            System.out.println("Quantidade Atualizada: " + qtdAtualizada);

//            System.out.println("Chamando adicionarEstoque com ID: " + idProduto); // ID do produto

            if (qtdAtualizada > estoqueMaximo) {

                JOptionPane.showMessageDialog(null, "Estoque máximo ultrapassado!");

                return;

            }



            if (qtdAtualizada < estoqueMinimo) {

                JOptionPane.showMessageDialog(null, "Estoque abaixo do mínimo, é necessário efetuar uma nova compra.");

            }



            //Logs para depuração

            //System.out.println("Qtd Atual: " + qtdAtual + ", Preço Atual: " + precoAtual);

            //System.out.println("Qtd Nova: " + qtdNova + ", Preço Novo: " + precoNovo);

            // Calcular preço médio de custo

            double precoMedioCusto = (((qtdAtual * precoAtual) + (qtdNova * precoNovo)) / (qtdAtual + qtdNova)) / 100;

            BigDecimal precoMedioArredondado = new BigDecimal(precoMedioCusto).setScale(2, RoundingMode.HALF_UP);



            // Chamada ao método para adicionar estoque

            ProdutosDAO daop = new ProdutosDAO();

            daop.adicionarEstoque(conn, idProduto, qtdNova, precoMedioArredondado.doubleValue());



            // Limpa os campos do formulário

            new LimpaTela().LimpaTela(painel_estoque);



            JOptionPane.showMessageDialog(null, "Estoque Atualizado: ");



        } catch (NumberFormatException ex) {

            JOptionPane.showMessageDialog(null, "Erro de conversão de número: " + ex.getMessage());

        } catch (SQLException | ClassNotFoundException ex) {

            JOptionPane.showMessageDialog(null, "Erro ao adicionar: " + ex.getMessage());

        } finally {

            if (conn != null) {

                try {

                    conn.close(); // Fecha a conexão no final

                } catch (SQLException e) {

                    e.printStackTrace();

                }

            }

        }

    }//GEN-LAST:event_btnAdicionarActionPerformed



    public static double parseStringToDouble(String valor) throws ParseException {

        // Remove o símbolo de moeda e espaços

        String valorLimpo = valor.replace("R$", "").replace("\u00A0", "").trim();



        // Substitui a vírgula decimal por ponto e remove separadores de milhar

        valorLimpo = valorLimpo.replace(".", "").replace(",", ".");



        // Converte para double

        return Double.parseDouble(valorLimpo);

    }



