    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        Produtos obj = new Produtos();

        obj.setId(Integer.parseInt(txtCodigo.getText()));

        obj.setDescricao(txtDescricao.getText());



        // Obtenha o preço do txtQtdAtual como um valor double

        double preco = Double.parseDouble(txtQtdAtual.getText().replace("R$", "").replace(".", "").replace(",", "."));

        obj.setPreco(preco);



        obj.setQtd_estoque(Integer.parseInt(txtQtd_Nova.getText()));



        try {

            if (fornecedorSelecionado != null) {

                obj.setCliFor(fornecedorSelecionado); // Usa o fornecedor armazenado

            }



            ProdutosDAO daop = new ProdutosDAO();

            daop.Editar(obj);

            LimpaTela util = new LimpaTela();

            util.LimpaTela(painel_estoque);

        } catch (SQLException | ClassNotFoundException ex) {

            Logger.getLogger(Form_Estoque.class.getName()).log(Level.SEVERE, null, ex);

        }

    }//GEN-LAST:event_btnEditarActionPerformed



