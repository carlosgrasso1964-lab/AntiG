    public void listar() throws SQLException, ClassNotFoundException {



        ProdutosDAO dao = new ProdutosDAO();

        List<Produtos> lista = dao.Listar();

        DefaultTableModel dados = (DefaultTableModel) tabela.getModel();

        dados.setNumRows(0);



        // Configura o formato de moeda brasileira

        @SuppressWarnings("deprecation")

        NumberFormat nf = NumberFormat.getCurrencyInstance(new Locale("pt", "BR"));



        for (Produtos p : lista) {

            // Formata o preço do produto

            String precoFormatado = nf.format(p.getPrecoMedioCusto());



            // Formata a quantidade com 3 casas decimais

            String qtdEstoqueFormatada = String.format("%.3f", p.getQtd_estoque());

            String qtdEstoqueFormatadaMinima = String.format("%.3f", p.getQtd_estoqueMinimo());

            String qtdEstoqueFormatadaMaxima = String.format("%.3f", p.getQtd_estoqueMaximo());



            // Adiciona a linha na tabela com o preço e quantidade formatados

            dados.addRow(new Object[]{

                p.getId(),

                p.getDescricao(),

                precoFormatado, // Preço formatado como moeda

                qtdEstoqueFormatada, // Quantidade formatada com 3 casas decimais

                qtdEstoqueFormatadaMinima, // Quantidade formatada com 3 casas decimais

                qtdEstoqueFormatadaMaxima, // Quantidade formatada com 3 casas decimais

                p.getCliFor().getNomeCliFor()

            });

        }

    }



