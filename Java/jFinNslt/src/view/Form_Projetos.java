    private void jButtonLerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLerActionPerformed

        try {

            int id = Integer.parseInt(txtId.getText());

            Projeto projeto = projetoDAO.ler(id);



            if (projeto != null) {

                txtNome.setText(projeto.getNome());



                DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy"); // Adapte ao formato da sua interface



                if (projeto.getDataInicioPrevista() != null) {

                    txtInicioP.setText(projeto.getDataInicioPrevista().format(formatter));

                } else {

                    txtInicioP.setText(""); // Limpa o campo se a data for nula

                }



                if (projeto.getDataFimPrevista() != null) {

                    txtF.setText(projeto.getDataFimPrevista().format(formatter));

                } else {

                    txtF.setText("");

                }



                if (projeto.getDataInicioRealizada() != null) {

                    txtInicioR.setText(projeto.getDataInicioRealizada().format(formatter));

                } else {

                    txtInicioR.setText("");

                }



                if (projeto.getDataFimRealizada() != null) {

                    txtFR.setText(projeto.getDataFimRealizada().format(formatter));

                } else {

                    txtFR.setText("");

                }

                

                cbStatus.setSelectedItem(projeto.getStatus());

                

            } else {

                JOptionPane.showMessageDialog(this, "Projeto não encontrado.");

            }

        } catch (SQLException | NumberFormatException ex) {

            JOptionPane.showMessageDialog(this, "Erro ao ler projeto: " + ex.getMessage());

        }

    }//GEN-LAST:event_jButtonLerActionPerformed



    private void jButtonAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAtualizarActionPerformed

        try {

            Projeto projeto = new Projeto();

            projeto.setId(Integer.parseInt(txtId.getText()));

            projeto.setNome(txtNome.getText());

            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy"); // Adapte ao formato da sua interface

            try {

                if (!txtInicioP.getText().isEmpty()) {

                    projeto.setDataInicioPrevista(LocalDate.parse(txtInicioP.getText(), formatter));

                }

                if (!txtF.getText().isEmpty()) {

                    projeto.setDataFimPrevista(LocalDate.parse(txtF.getText(), formatter));

                }

                if (!txtInicioR.getText().isEmpty()) {

                    projeto.setDataInicioRealizada(LocalDate.parse(txtInicioR.getText(), formatter));

                }

                if (!txtFR.getText().isEmpty()) {

                    projeto.setDataFimRealizada(LocalDate.parse(txtFR.getText(), formatter));

                }

            } catch (DateTimeParseException ex) {

                JOptionPane.showMessageDialog(this, "Formato de data inválido. Use dd/MM/yyyy.", "Erro", JOptionPane.ERROR_MESSAGE);

                return; // Sai do método se houver erro de formatação

            }

            projeto.setStatus(cbStatus.getSelectedItem().toString());

            projetoDAO.atualizar(projeto);

            JOptionPane.showMessageDialog(this, "Projeto atualizado com sucesso!");

            carregarProjetos();

        } catch (SQLException | NumberFormatException ex) {

            JOptionPane.showMessageDialog(this, "Erro ao atualizar projeto: " + ex.getMessage());

        }

    }//GEN-LAST:event_jButtonAtualizarActionPerformed



