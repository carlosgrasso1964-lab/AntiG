    private void jButtonCriarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCriarActionPerformed

        try {

            Projeto projeto = new Projeto();

            projeto.setNome(txtNome.getText());



            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy"); // Adapte ao formato da sua interface



            try {

                if (!txtInicioP.getText().isEmpty()) {

                    projeto.setDataInicioPrevista(LocalDate.parse(txtInicioP.getText(), formatter));

                }

                if (!txtF.getText().isEmpty()) {

                    projeto.setDataFimPrevista(LocalDate.parse(txtF.getText(), formatter));

                }

                if (!txtInicioR.getText().isEmpty()) {

                    projeto.setDataInicioRealizada(LocalDate.parse(txtInicioR.getText(), formatter));

                }

                if (!txtFR.getText().isEmpty()) {

                    projeto.setDataFimRealizada(LocalDate.parse(txtFR.getText(), formatter));

                }

            } catch (DateTimeParseException ex) {

                JOptionPane.showMessageDialog(this, "Formato de data inválido. Use dd/MM/yyyy.", "Erro", JOptionPane.ERROR_MESSAGE);

                return; // Sai do método se houver erro de formatação

            }



            projeto.setStatus(cbStatus.getSelectedItem().toString());



            projetoDAO.criar(projeto);

            JOptionPane.showMessageDialog(this, "Projeto criado com sucesso!");

            carregarProjetos();

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this, "Erro ao criar projeto: " + ex.getMessage());

        }

    }//GEN-LAST:event_jButtonCriarActionPerformed



