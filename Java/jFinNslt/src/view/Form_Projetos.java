    private void carregarProjetos() {

        DefaultTableModel model = (DefaultTableModel) tabelaProjetos.getModel();

        model.setRowCount(0);



        try {

            List<Projeto> projetos = projetoDAO.listarTodos();

            for (Projeto projeto : projetos) {

                model.addRow(new Object[]{

                    projeto.getId(),

                    projeto.getNome(),

                    projeto.getDataInicioPrevista(),

                    projeto.getDataFimPrevista(),

                    projeto.getDataInicioRealizada(),

                    projeto.getDataFimRealizada(),

                    projeto.getStatus()

                });

            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this, "Erro ao carregar projetos: " + ex.getMessage());

        }

    }



