    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed

        String nome = txtProduto.getText();

        try {

            double estoque = Double.valueOf(txtEstoque.getText().replace(".", "").replace(",", "."));

            double quantidade = Double.valueOf(txtQtd.getText().replace(".", "").replace(",", "."));



            String precoText = txtPreco.getText();

            //System.out.println("Preço no campo txtPreco: " + precoText);



            // Utiliza NumberFormat para parsear a string de moeda

            @SuppressWarnings("deprecation")

            NumberFormat nf = NumberFormat.getCurrencyInstance(new Locale("pt", "BR"));

            Number number = nf.parse(precoText);

            double preco = number.doubleValue();

            //System.out.println("Preço após parse: " + preco);



            double subtotal = preco * quantidade;

            total += subtotal; // Acumula o total da venda



            // Verifica se a quantidade é maior que o estoque

            if (estoque >= quantidade) {

                txtTotalVenda.setText(formatarDoubleParaMoeda(total)); // Formata o total em moeda



                // Recupera o ID do produto com base no nome

                ProdutosDAO produtosDAO = new ProdutosDAO();

                Produtos obj = produtosDAO.buscarPorNome(nome); // Método que retorna o produto pelo nome

                if (obj == null) {

                    JOptionPane.showMessageDialog(this, "Produto não encontrado no sistema!");

                    return;

                }



                // Adiciona o produto na tabela

                meus_produtos.addRow(new Object[]{

                    obj.getId(), // Adiciona o ID do produto

                    obj.getDescricao(),

                    String.format("%.3f", quantidade).replace(".", ","), // Formata a quantidade

                    formatarDoubleParaMoeda(preco), // Formata o preço em moeda

                    formatarDoubleParaMoeda(subtotal) // Formata o subtotal em moeda

                });



                // Cria um objeto ItensVendas e adiciona na lista

                ItensVendas itemVenda = new ItensVendas();

                itemVenda.setProdutos(obj); // Associa o produto completo

                itemVenda.setQtd(quantidade);

                itemVenda.setSubtotal(subtotal);

                itensVendas.add(itemVenda); // Armazena na lista de itens da venda

            } else {

                JOptionPane.showMessageDialog(null, "Quantidade é maior que o seu estoque!!!");

            }

        } catch (NumberFormatException ex) {

            JOptionPane.showMessageDialog(null, "Verifique os valores inseridos! Eles devem ser válidos.");

        } catch (HeadlessException | ClassNotFoundException | SQLException | ParseException ex) {

            Logger.getLogger(Form_Vendas.class.getName()).log(Level.SEVERE, null, ex);

        }

    }//GEN-LAST:event_btnAdicionarActionPerformed





    private void btnPagamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagamentoActionPerformed

        String nome = "";

        if (cbxClientes.getSelectedItem() != null) {

            nome = cbxClientes.getSelectedItem().toString();

        } else {

            JOptionPane.showMessageDialog(this, "Nenhum cliente selecionado!");

            return; // Sai do método caso não tenha cliente selecionado

        }

        String cpf = txtCpf.getText();

        CliFor obj = new CliFor();

        CliForDAO daoc;

        try {

            daoc = new CliForDAO();

            obj = daoc.BuscarCliente(nome);

            obj = daoc.BuscarClienteCPF(cpf);

            if (obj.getNomeCliFor()!= null && obj.getCpf() != null) {

                Form_Pagamentos telaPag = new Form_Pagamentos();

                telaPag.clientes = obj;



                // Passar o modelo de tabela para o FormularioPagamentos

                telaPag.setMeusProdutos(meus_produtos);



                // Crie uma lista de ItensVendas e preencha com os produtos selecionados

                List<ItensVendas> itensVendas = new ArrayList<>();

                for (int i = 0; i < meus_produtos.getRowCount(); i++) {

                    ItensVendas item = new ItensVendas();

                    Produtos p = new Produtos();



                    // Verificar se o valor do ID não é nulo antes de converter

                    Object idValue = meus_produtos.getValueAt(i, 0);

                    if (idValue == null) {

                        JOptionPane.showMessageDialog(this, "Erro: Produto sem ID na linha " + (i + 1));

                        continue; // Pule esta iteração do loop

                    }



                    p.setId(Integer.valueOf(idValue.toString()));  // Id do produto



                    // Verificar se a quantidade não é nula

                    Object qtdValue = meus_produtos.getValueAt(i, 2);

                    if (qtdValue == null) {

                        JOptionPane.showMessageDialog(this, "Erro: Produto sem quantidade na linha " + (i + 1));

                        continue;

                    }

                    item.setQtd(Double.valueOf(qtdValue.toString().replace(".", "").replace(",", ".")));  // Quantidade



                    // Verificar se o subtotal não é nulo

                    Object subtotalValue = meus_produtos.getValueAt(i, 4);

                    if (subtotalValue == null) {

                        JOptionPane.showMessageDialog(this, "Erro: Produto sem subtotal na linha " + (i + 1));

                        continue;

                    }

                    double subtotal = formatarMoedaParaDouble(subtotalValue.toString());

                    item.setSubtotal(subtotal);



                    item.setProdutos(p);

                    itensVendas.add(item);

                }



                // Passa a lista de itens de venda para o FormularioPagamentos

                telaPag.itensVendas = itensVendas;



                // Formata diretamente o valor total para moeda e exibe no campo txtTotalVenda

                telaPag.txtTotalVenda.setText(formatarDoubleParaMoeda(total));



                // Exibe o formulário de pagamento

                telaPag.setVisible(true);

                this.dispose();

            } else {

                JOptionPane.showMessageDialog(null, "Verifique se esqueceu alguma informação(NOME e/ou CPF)!");

            }



        } catch (SQLException | ClassNotFoundException ex) {

            Logger.getLogger(Form_Vendas.class.getName()).log(Level.SEVERE, null, ex);

        }

    }//GEN-LAST:event_btnPagamentoActionPerformed



