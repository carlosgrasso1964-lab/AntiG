    private void cbxClientesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbxClientesActionPerformed



        // Obtém o valor selecionado

        String selectedValue = cbxClientes.getSelectedItem().toString().trim();

        //System.out.println("Selected Value: " + selectedValue);



        // Localiza o primeiro traço no valor selecionado

        int indexDoTraco = selectedValue.indexOf("-");

        if (indexDoTraco != -1) {

            // Pega tudo que vem após o traço

            String documentoCompleto = selectedValue.substring(indexDoTraco + 1).trim(); // Remove espaços adicionais



            //System.out.println("Documento extraído: " + documentoCompleto);



            // Verifica o tamanho do documento para identificar CPF ou CNPJ

            if (documentoCompleto.length() == 14) {

                txtCpf.setText(documentoCompleto); // Preenche como CPF

                //System.out.println("Documento identificado como CPF: " + documentoCompleto);

            } else if (documentoCompleto.length() == 18) {

                txtCpf.setText(documentoCompleto); // Preenche como CNPJ

                //System.out.println("Documento identificado como CNPJ: " + documentoCompleto);

            } else {

                JOptionPane.showMessageDialog(this, "Documento inválido! Verifique o formato.");

            }

        } else {

            JOptionPane.showMessageDialog(this, "Formato inválido: cliente selecionado não contém um CPF ou CNPJ!");

        }

    }//GEN-LAST:event_cbxClientesActionPerformed



    private String formatarCPF(String cpf) {

        try {

            MaskFormatter formatter = new MaskFormatter("###.###.###-##");

            formatter.setValueContainsLiteralCharacters(false);

            return formatter.valueToString(cpf.replaceAll("\\D", "")); // Remove caracteres não numéricos antes de formatar

        } catch (Exception e) {

            e.printStackTrace();

            return cpf; // Retorna o CPF sem formatação em caso de erro

        }

    }



    private double formatarMoedaParaDouble(String valor) {

        try {

            // Exibe o valor original para análise

            //System.out.println("Valor original antes de limpar: " + valor);



            // Remove o números "R$", remove todos os tipos de espaço (incluindo espaços invisíveis), pontos e vírgulas

            String valorLimpo = valor.replace("R$", "").replace("\u00A0", "").trim().replace(".", "").replace(",", ".");



            // Exibe o valor limpo antes de converter

            //System.out.println("Valor limpo: " + valorLimpo);

            return Double.parseDouble(valorLimpo);

        } catch (NumberFormatException e) {

            System.out.println("Erro ao converter o valor: " + valor);

            return 0;

        }

    }



    public String formatarDoubleParaMoeda(double valor) {

        @SuppressWarnings("deprecation")

        NumberFormat nf = NumberFormat.getNumberInstance(new Locale("pt", "BR"));

        nf.setMinimumFractionDigits(2);

        nf.setMaximumFractionDigits(2);

        return nf.format(valor);

    }



