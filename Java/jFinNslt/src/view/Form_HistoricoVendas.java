    private void btnPesquisarVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarVendaActionPerformed

        DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");

        try {

            // Parse das datas de início e fim

            LocalDate data_inicio = LocalDate.parse(txtInicio.getText(), formato);

            LocalDate data_fim = LocalDate.parse(txtFim.getText(), formato);



            // Instanciar o DAO e fazer a consulta

            VendasDAO vd = new VendasDAO();

            List<Vendas> lista = vd.historicoVendas(data_inicio, data_fim); // Agora reconhece SQLException



            // Atualizar a tabela

            DefaultTableModel historico = (DefaultTableModel) tabela.getModel();

            historico.setNumRows(0); // Limpar tabela anterior



            // Define o formato para moeda no padrão brasileiro

            NumberFormat nf = NumberFormat.getCurrencyInstance();

            double faturamentoAcumulado = 0.0;



            for (Vendas v : lista) {

                // Formata o preço de Total da Venda

                String Total_vendaFormatado = nf.format(v.getTotal_venda());



                // Atualiza o Faturamento Acumulado

                faturamentoAcumulado += v.getTotal_venda();

                String FaturamentoAcumuladoFormatado = nf.format(faturamentoAcumulado);



                // Adiciona a nova linha com a coluna Faturamento Acumulado

                historico.addRow(new Object[]{

                    v.getId(),

                    v.getClientes().getNomeCliFor(),

                    v.getData_venda(),

                    Total_vendaFormatado,

                    FaturamentoAcumuladoFormatado, // Nova coluna com o Faturamento Acumulado

                    v.getObservacoes()

                });

            }

        } catch (DateTimeParseException ex) {

            Logger.getLogger(Form_HistoricoVendas.class.getName()).log(Level.SEVERE, "Erro ao parsear as datas!", ex);

            JOptionPane.showMessageDialog(null, "Formato de data inválido! Use dd/MM/yyyy.");

        } catch (SQLException ex) {

            Logger.getLogger(Form_HistoricoVendas.class.getName()).log(Level.SEVERE, "Erro ao consultar as vendas!", ex);

            JOptionPane.showMessageDialog(null, "Erro ao consultar as vendas: " + ex.getMessage());

        }

    }//GEN-LAST:event_btnPesquisarVendaActionPerformed



