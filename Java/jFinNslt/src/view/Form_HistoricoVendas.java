    private void gerarRelatorioPDF(List<Vendas> lista, NumberFormat nf, LocalDate data_inicio, LocalDate data_fim) throws FileNotFoundException, DocumentException, IOException {



        // Obtém o caminho para a área de Trabalho

        String desktopPath = javax.swing.filechooser.FileSystemView.getFileSystemView().getHomeDirectory().getAbsolutePath();



        // Configuração do JFileChooser

        JFileChooser fileChooser = new JFileChooser();

        fileChooser.setDialogTitle("Salvar Relatório");

        fileChooser.setCurrentDirectory(new File(desktopPath)); // Define a área de Trabalho como diretório inicial



        // Exibe a janela para o usuário escolher o local e nome do arquivo

        int escolha = fileChooser.showSaveDialog(null);

        if (escolha != JFileChooser.APPROVE_OPTION) {

            return; // Sai do método se o usuário cancelar a operação

        }



        // Recupera o arquivo selecionado e garante a extensão .pdf

        File arquivo = fileChooser.getSelectedFile();

        if (!arquivo.getName().endsWith(".pdf")) {

            arquivo = new File(arquivo.getAbsolutePath() + ".pdf");

        }



        // Criação do documento PDF

        Document document = new Document();

        PdfWriter writer = PdfWriter.getInstance(document, new FileOutputStream(arquivo));

        document.open();



        // Adiciona a imagem

        Image imagem = null;

        try {

            imagem = Image.getInstance("src/Imagens/Home.png"); // Certifique-se do caminho da imagem

            imagem.scaleAbsolute(45f, 50f);

            imagem.setAlignment(Element.ALIGN_LEFT);

            document.add(imagem);

        } catch (DocumentException | IOException e) {

            JOptionPane.showMessageDialog(null, "Imagem não encontrada: " + e.getMessage());

        }



        // Adiciona título com a data

        String titulo = "Faturamento referente ao período de: " + data_inicio.format(DateTimeFormatter.ofPattern("dd/MM/yyyy"))

                + " até " + data_fim.format(DateTimeFormatter.ofPattern("dd/MM/yyyy"));

        Paragraph pTitulo = new Paragraph(titulo, new Font(Font.FontFamily.HELVETICA, 14, Font.BOLD));

        pTitulo.setAlignment(Element.ALIGN_CENTER);

        document.add(pTitulo);

        document.add(new Chunk("\n")); // Espaço entre o título e a tabela



        // Criação da tabela no PDF

        PdfPTable tabelaPDF = new PdfPTable(6);

        tabelaPDF.setWidths(new float[]{1, 3, 2, 2, 2, 3}); // Ajuste das larguras das colunas

        tabelaPDF.addCell("ID Venda");

        tabelaPDF.addCell("Nome Cliente");

        tabelaPDF.addCell("Data Venda");

        tabelaPDF.addCell("Total Venda");

        tabelaPDF.addCell("Fat.Acum.");

        tabelaPDF.addCell("Obs.");



        double faturamentoAcumulado = 0.0;

        for (Vendas v : lista) {

            tabelaPDF.addCell(new PdfPCell(new Phrase(String.valueOf(v.getId())))); // ID Cliente

            tabelaPDF.addCell(new PdfPCell(new Phrase(v.getClientes().getNomeCliFor()))); // Nome Cliente



            // Formata a data

            try {

                if (v.getData_venda() != null && !v.getData_venda().isEmpty()) {

                    LocalDate dataVenda = LocalDate.parse(v.getData_venda(), DateTimeFormatter.ofPattern("dd/MM/yyyy"));

                    tabelaPDF.addCell(new PdfPCell(new Phrase(dataVenda.format(DateTimeFormatter.ofPattern("dd/MM/yyyy")))));

                } else {

                    tabelaPDF.addCell(new PdfPCell(new Phrase("Data Inválida")));

                }

            } catch (DateTimeParseException e) {

                System.err.println("Erro ao parsear a data: " + v.getData_venda());

                tabelaPDF.addCell(new PdfPCell(new Phrase("Data Inválida")));

            }



            // Formata o total da venda

            String totalVendaFormatado = nf.format(v.getTotal_venda());

            tabelaPDF.addCell(new PdfPCell(new Phrase(totalVendaFormatado)));



            // Calcula e formata o faturamento acumulado

            faturamentoAcumulado += v.getTotal_venda();

            String faturamentoAcumuladoFormatado = nf.format(faturamentoAcumulado);

            tabelaPDF.addCell(new PdfPCell(new Phrase(faturamentoAcumuladoFormatado)));



            // Observações

            tabelaPDF.addCell(new PdfPCell(new Phrase(v.getObservacoes() != null ? v.getObservacoes() : "")));

        }

        // Adiciona rodapé no PDF

        writer.setPageEvent(new PdfPageEventHelper() {

            @Override

            public void onEndPage(PdfWriter writer, Document document) {

                String footerText = "Gerado em " + LocalDate.now().format(DateTimeFormatter.ofPattern("dd/MM/yyyy"))

                        + " - Pág. " + writer.getPageNumber();

                ColumnText.showTextAligned(writer.getDirectContent(), Element.ALIGN_RIGHT, new Phrase(footerText),

                        document.right() - 30, document.bottom() - 10, 0); // Ajusta o rodapé à direita

            }

        });



        document.add(tabelaPDF);

        document.close();

        

        JOptionPane.showMessageDialog(null, "Relatório gerado com sucesso em: " + arquivo.getAbsolutePath());



        // Abre o PDF para visualização

        Desktop.getDesktop().open(arquivo);

    }



