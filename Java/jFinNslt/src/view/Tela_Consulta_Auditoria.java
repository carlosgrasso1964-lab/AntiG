    private void jButtonAnalisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAnalisarActionPerformed

        String campoData = jRadioButtonVcto.isSelected() ? "dtVcto" : "dtApr";

        // O filtro de data é aplicado individualmente para não haver "perda" de somas.
        // O segredo está em tirar o "p.mes = m.mes" do JOIN
        String sql = "SELECT "
                + "    p.conta AS 'Grupo de Conta', "
                + "    ROUND(SUM(p.valor_planejado), 2) AS 'Previsto', " // Aqui ele vai somar são os meses filtrados no WHERE
                + "    ROUND(COALESCE(m.TotalRealizado, 0), 2) AS 'Realizado', "
                + "    ROUND((COALESCE(m.TotalRealizado, 0) - SUM(p.valor_planejado)), 2) AS 'Desvio Abs.', "
                + "    CASE WHEN SUM(p.valor_planejado) = 0 THEN 0 "
                + "    ELSE ROUND(((COALESCE(m.TotalRealizado, 0) / SUM(p.valor_planejado)) - 1) * 100, 2) END AS 'Var %' "
                + "FROM tb_plano_diretor p "
                + "LEFT JOIN ("
                + "    SELECT nome_C, SUM(Valor) as TotalRealizado "
                + "    FROM viewmovrd "
                + "    WHERE Prev = 'V' "
                + "      AND " + campoData + " BETWEEN ? AND ? " // Parâmetros 1 e 2
                + "    GROUP BY nome_C"
                + ") m ON REPLACE(REPLACE(p.conta, ' ', ''), '.', '') = REPLACE(REPLACE(m.nome_C, ' ', ''), '.', '') "
                + "WHERE p.ano_referencia = 2026 "
                + "  AND p.mes BETWEEN CAST(strftime('%m', ?) AS INTEGER) AND CAST(strftime('%m', ?) AS INTEGER) " // Parâmetros 3 e 4
                + "  AND p.conta NOT LIKE 'Receitas%' "
                + "  AND p.conta NOT LIKE 'Despesas%' "
                + "  AND p.conta NOT LIKE 'Saldo%' "
                + "  AND p.conta NOT LIKE 'Resultado%' "
                + "GROUP BY p.conta "
                + "ORDER BY ABS(COALESCE(m.TotalRealizado, 0) - SUM(p.valor_planejado)) DESC";
        try {
            java.sql.Connection con = conexao.getConexao();
            java.sql.PreparedStatement pst = con.prepareStatement(sql);

            String dataIni = formatarDataParaBanco(jFormattedTextFieldDataIni.getText());
            String dataFim = formatarDataParaBanco(jFormattedTextFieldDataFim.getText());

            // Agora são 4 parâmetros na ordem do SQL acima
            pst.setString(1, dataIni); // Para o m.dtVcto BETWEEN
            pst.setString(2, dataFim); // Para o m.dtVcto BETWEEN
            pst.setString(3, dataIni); // Para o p.mes BETWEEN
            pst.setString(4, dataFim); // Para o p.mes BETWEEN

            java.sql.ResultSet rs = pst.executeQuery();
            jTablePesquisa.setModel(net.proteanit.sql.DbUtils.resultSetToTableModel(rs));

        } catch (Exception e) {
            e.printStackTrace(); // Importante para ver o erro no console do NetBeans
            JOptionPane.showMessageDialog(null, "Erro ao processar auditoria: " + e.getMessage());
        }
    }

    // Método auxiliar para converter dd/MM/yyyy para yyyy-MM-dd (Padrão SQLite)
    private String formatarDataParaBanco(String dataBr) {
        try {
            String[] partes = dataBr.split("/");
            return partes[2] + "-" + partes[1] + "-" + partes[0];
        } catch (Exception e) {
            return "";
        }

    }//GEN-LAST:event_jButtonAnalisarActionPerformed


