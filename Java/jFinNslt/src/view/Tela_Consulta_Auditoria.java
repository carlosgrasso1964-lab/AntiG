    private void enviarParaLia(String prompt) {
        new Thread(() -> {
            try {
                // Rota de geração simples, sem histórico (mais leve)
                @SuppressWarnings("deprecation")
                java.net.URL url = new java.net.URL("http://127.0.0.1:11434/api/generate");
                java.net.HttpURLConnection conn = (java.net.HttpURLConnection) url.openConnection();
                conn.setRequestMethod("POST");
                conn.setRequestProperty("Content-Type", "application/json");
                conn.setDoOutput(true);

                // Timeout de conexão curto, mas SEM timeout de leitura (infinito)
                conn.setConnectTimeout(10000);
                conn.setReadTimeout(0);

                // Escapa barras invertidas, aspas, quebras de linha e retornos de carro
                String promptEscapado = prompt.replace("\\", "\\\\")
                        .replace("\"", "\\\"")
                        .replace("\n", "\\n")
                        .replace("\r", "\\r")
                        .replace("\t", "\\t");

                String jsonInputString = "{"
                        + "\"model\": \"gemma2:2b\","
                        + "\"prompt\": \" " + promptEscapado + "\","
                        + "\"stream\": false"
                        + "}";

//                String jsonInputString = "{"
//                        + "\"model\": \"gemma2:2b\","
//                        + "\"prompt\": \"" + prompt.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\","
//                        + "\"stream\": false" // Deixamos false para simplificar o split, mas com timeout 0
//                        + "}";

                //System.out.println("JSON Enviado: " + jsonInputString);

                try (java.io.OutputStream os = conn.getOutputStream()) {
                    os.write(jsonInputString.getBytes("utf-8"));
                }

                // O Java vai ficar parado aqui o tempo que for preciso sem dar erro
                java.util.Scanner s = new java.util.Scanner(conn.getInputStream(), "UTF-8").useDelimiter("\\A");
                String response = s.hasNext() ? s.next() : "";

                // Extração simplificada da resposta
                String finalAnswer = response.split("\"response\":\"")[1].split("\",\"done\"")[0];
                finalAnswer = finalAnswer.replace("\\n", "\n").replace("\\\"", "\"");

                final String resultado = finalAnswer;
                javax.swing.SwingUtilities.invokeLater(() -> {
                    // Se estiver dentro de uma classe anônima, use NomeDaSuaTela.this.setCursor(...)
                    setCursor(java.awt.Cursor.getDefaultCursor());
                    // Salva automaticamente para não perder a análise
                    // 2. Salva sozinho na pasta do executável
                    salvarParecerAutomatico(resultado);

                    javax.swing.JTextArea textArea = new javax.swing.JTextArea(20, 50);
                    textArea.setText(resultado);
                    textArea.setLineWrap(true);
                    textArea.setWrapStyleWord(true);
                    JOptionPane.showMessageDialog(null, new javax.swing.JScrollPane(textArea), "Parecer da Lia", 1);
                });

            } catch (Exception e) {
                e.printStackTrace();
                javax.swing.SwingUtilities.invokeLater(() -> {
                    JOptionPane.showMessageDialog(null, "Lia está exausta (Erro): " + e.getMessage());
                });
            }
        }).start();

    }

    private double buscarInflacaoPremissa() {
        double inflacao = 5.0; // Valor padrão caso falhe
        String sql = "SELECT inflacao_premissa FROM tb_plano_diretor LIMIT 1";
        try (java.sql.Connection con = new Conexao().getConexao(); // Use sua classe de conexão
                 java.sql.PreparedStatement pst = con.prepareStatement(sql); java.sql.ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                inflacao = rs.getDouble("inflacao_premissa");
            }
        } catch (Exception e) {
            System.err.println("Erro ao buscar inflação: " + e.getMessage());
        }
        return inflacao;
    }

    private void salvarParecerAutomatico(String texto) {
        try {
            // Criamos uma pasta 'analises_lia' para não bagunçar a pasta raiz
            java.io.File pasta = new java.io.File("analises_lia");
            if (!pasta.exists()) {
                pasta.mkdir(); // Cria a pasta se ela não existir
            }

            String dataHora = new java.text.SimpleDateFormat("yyyyMMdd_HHmm").format(new java.util.Date());
            String nomeArquivo = "analises_lia/Parecer_" + dataHora + ".txt";

            java.io.File arquivo = new java.io.File(nomeArquivo);
            try (java.io.PrintWriter out = new java.io.PrintWriter(new java.io.FileWriter(arquivo))) {
                out.println("AUDITORIA LIA - JFINNSLT");
                out.println("DATA: " + new java.text.SimpleDateFormat("dd/MM/yyyy HH:mm:ss").format(new java.util.Date()));
                out.println("------------------------------------------\n");
                out.println(texto);
                out.flush();
            }
            // Log apenas no console do NetBeans para você saber que funcionou
            System.out.println("Parecer arquivado em: " + arquivo.getAbsolutePath());

        } catch (java.io.IOException e) {
            System.err.println("Erro ao arquivar parecer: " + e.getMessage());
        }
    }

