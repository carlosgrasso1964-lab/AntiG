    private void jButtonTransferirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTransferirActionPerformed



          try {

            String data = jFormattedData.getText();

            String documento = jTextFieldDoc.getText();

            double valor = Double.parseDouble(jTextFieldValor.getText().replace(",", "."));

            

            Transferencia transferencia = new Transferencia(

                jTextFieldOnr.getText(),

                jTextFieldOclass.getText(),

                jTextFieldDnr.getText(),

                jTextFieldDclass.getText(),

                documento,

                data,

                valor

            );



            boolean sucesso = transferenciaDAO.registrarTransferencia(transferencia);

            

            if (sucesso) {

                JOptionPane.showMessageDialog(this, "Transferência efetuada com sucesso!");

                limparCampos();

            } else {

                JOptionPane.showMessageDialog(this, "Erro ao realizar a transferência!");

            }



        } catch (NumberFormatException ex) {

            JOptionPane.showMessageDialog(this, "Valor inválido! Verifique o formato do número.");

        }  

    }//GEN-LAST:event_jButtonTransferirActionPerformed

    

