    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed

        int Parcelas = Integer.parseInt(jTextFieldParcelas.getText());

        BigDecimal Princ = BigDecimal.ZERO;
        BigDecimal LiqParc = BigDecimal.ZERO;
        BigDecimal difer = BigDecimal.ZERO;

        BigDecimal comparaCompra = new BigDecimal(jTextFieldVrCompra.getText().replaceAll(",", "."));

        int i = 0;
        int idsc = 0;

        if (comparaCompra.compareTo(BigDecimal.ZERO) == 0) {

            BigDecimal vrParcela = new BigDecimal(jTextFieldVrParcela.getText());
            Princ = vrParcela.multiply(new BigDecimal(Parcelas));
            LiqParc = vrParcela;

        } else {

            Princ = new BigDecimal(jTextFieldVrCompra.getText().replaceAll(",", "."));

            BigDecimal meValor = Princ.divide(new BigDecimal(Parcelas), 10, RoundingMode.HALF_UP);
            BigDecimal Valor = meValor.setScale(2, RoundingMode.FLOOR);

            LiqParc = Valor;

            BigDecimal pc = new BigDecimal(Parcelas);
            BigDecimal vrParcD = Princ.subtract(Valor.multiply(pc)).setScale(2, RoundingMode.FLOOR);

            difer = vrParcD;

            if (difer.compareTo(BigDecimal.ZERO) != 0) {

                String msg = "Diferença de " + difer + " encontrada.\n"
                        + "Em qual parcela (1 a " + Parcelas + ") deseja lançar?";

                String escolha = JOptionPane.showInputDialog(null, msg);

                try {
                    if (escolha != null && !escolha.isEmpty()) {
                        idsc = Integer.parseInt(escolha);

                        if (idsc < 1 || idsc > Parcelas) {
                            idsc = 1;
                            JOptionPane.showMessageDialog(null, "Parcela inválida! Será usada a parcela 1.");
                        }
                    } else {
                        idsc = 1;
                    }
                } catch (Exception e) {
                    idsc = 1;
                    JOptionPane.showMessageDialog(null, "Entrada inválida. Será usada a parcela 1.");
                }
            }
        }

        String opc = buttonGroup1.getSelection().getActionCommand();

        Object[] options = {"Sim", "Não"};
        int i1 = JOptionPane.showOptionDialog(null, "Corrige Data da Emissão?", "Corrige Emissão",
                JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE, null, options, options[0]);

        boolean corrigeEmi = (i1 == JOptionPane.YES_OPTION);

        SimpleDateFormat dateFormat = new SimpleDateFormat("dd/MM/yyyy");
        SimpleDateFormat sdfBanco = new SimpleDateFormat("yyyy-MM-dd");

        try {

            conexao.abrirConexao();
            Connection con = conexao.getConexao();

            con.setAutoCommit(false);

            try {

                Calendar calEmi = Calendar.getInstance();
                Calendar calVcto = Calendar.getInstance();

                calEmi.setTime(dateFormat.parse(jFormattedTextFieldEmissao.getText()));
                calVcto.setTime(dateFormat.parse(jFormattedTextFieldVencimento.getText()));

                for (i = 0; i < Parcelas; i++) {

                    if (i > 0) {

                        int field = Calendar.MONTH;
                        int amount = 0;

                        if ("1".equals(opc)) {
                            amount = 1;
                        } else if ("2".equals(opc)) {
                            amount = 3;
                        } else if ("3".equals(opc)) {
                            amount = 2;
                        } else if ("4".equals(opc)) {
                            field = Calendar.YEAR;
                            amount = 1;
                        } else if ("5".equals(opc)) {
                            field = Calendar.WEEK_OF_YEAR;
                            amount = 1;
                        } else if ("6".equals(opc)) {
                            field = Calendar.DAY_OF_MONTH;
                            amount = 1;
                        } else if ("7".equals(opc)) {
                            amount = 4;
                        }

                        calVcto.add(field, amount);

                        if (corrigeEmi) {
                            calEmi.add(field, amount);
                        }
                    }

                    // ? CONVERSÃO PARA STRING (SOLUÇÃO DO PROBLEMA)
                    String dataEmi = sdfBanco.format(calEmi.getTime());
                    String dataVcto = sdfBanco.format(calVcto.getTime());

                    executarInsert(con, dataEmi, dataVcto, i, Parcelas, LiqParc, difer, idsc, "1");
                    executarInsert(con, dataEmi, dataVcto, i, Parcelas, LiqParc, difer, idsc, "2");
                    executarInsert(con, dataEmi, dataVcto, i, Parcelas, LiqParc, difer, idsc, "3");
                }

                con.commit();

                JOptionPane.showMessageDialog(null, "Parcelamento gerado com sucesso!");

                // Limpeza dos campos
                jTextFieldVrCompra.setText("");
                jTextFieldParcelas.setText("");
                jTextFieldNrFav.setText("");
                jTextFieldClassFav.setText("");
                jTextFieldVClass.setText("");
                jTextFieldDoc.setText("");
                jFormattedTextFieldEmissao.setText("");
                jFormattedTextFieldVencimento.setText("");
                jTextFieldVrParcela.setText("");
                jTextFieldDescricao.setText("");
                jTextFieldStatus.setText("");
                jTextFieldPrev.setText("");
                jComboBoxClass.setSelectedIndex(0);
                jComboBoxFav.setSelectedIndex(0);

            } catch (Exception e) {
                con.rollback();
                throw e;
            }

        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Erro: " + ex.getMessage());
        }

    }//GEN-LAST:event_jButtonGerarActionPerformed

private void executarInsert(Connection con, String dataEmi, String dataVcto,
            int i, int totalParc, BigDecimal liq, BigDecimal dif, int idsc, String tipoIns) throws SQLException {

        String sql = "INSERT INTO tbmovimento(recurso,vrecurso,clifor,vCliFor,dtlancto,dtEmi,dtVcto,documento,classif,Descr,valor,dtApr,statusMov,Prev) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)";

        try (PreparedStatement stmt = con.prepareStatement(sql)) {

            BigDecimal valorFinal = liq;
            if ((i + 1) == idsc) {
                valorFinal = liq.add(dif);
            }

            valorFinal = valorFinal.abs();
            
            if (tipoIns.equals("1")) {
                stmt.setString(1, "0079");
                stmt.setString(2, "2.001.003");
                stmt.setBigDecimal(11, valorFinal.negate());
            } else if (tipoIns.equals("2")) {
                stmt.setString(1, "0079");
                stmt.setString(2, "2.001.003");
                stmt.setBigDecimal(11, valorFinal.abs());
            } else {
                stmt.setString(1, tfNrRecurso.getText());
                stmt.setString(2, "2.001.003");
                stmt.setBigDecimal(11, valorFinal.negate());
            }

            stmt.setString(3, jTextFieldNrFav.getText());
            stmt.setString(4, jTextFieldClassFav.getText());
            stmt.setString(5, dataEmi);
            stmt.setString(6, dataEmi);
            stmt.setString(7, dataVcto);
            stmt.setString(8, jTextFieldDoc.getText());
            stmt.setString(9, tipoIns.equals("1") ? jTextFieldVClass.getText() : "9.001.003");
            stmt.setString(10, "parc." + (i + 1) + "/" + totalParc + " - " + jTextFieldDescricao.getText());

            if (tipoIns.equals("3")) {
                stmt.setNull(12, java.sql.Types.VARCHAR);
                stmt.setString(13, "");
            } else {
                stmt.setString(12, dataVcto);
                stmt.setString(13, "PG");
            }

            stmt.setString(14, jTextFieldPrev.getText());
            stmt.executeUpdate();
        }
}


