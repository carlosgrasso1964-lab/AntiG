    public void gerarCupomPDF() {



        JFileChooser fileChooser = new JFileChooser();

        fileChooser.setDialogTitle("Salvar Cupom Não Fiscal");

        fileChooser.setFileFilter(new FileNameExtensionFilter("PDF Files", "pdf"));



        int userSelection = fileChooser.showSaveDialog(null);

        if (userSelection == JFileChooser.APPROVE_OPTION) {

            String file_name = fileChooser.getSelectedFile().getAbsolutePath();

            // Adiciona a extensão .pdf se o usuário não o fizer

            if (!file_name.toLowerCase().endsWith(".pdf")) {

                file_name += ".pdf";

            }



            Document document = new Document(PageSize.A4);

            document.setMargins(10f, 10f, 10f, 10f);

            try {

                PdfWriter.getInstance(document, new FileOutputStream(file_name));

                document.open();



                // Adiciona a imagem

                Image imagem = null;

                try {

                    imagem = Image.getInstance("src/Imagens/Home.png"); // Certifique-se do caminho da imagem

                    imagem.scaleAbsolute(45f, 50f);

                    imagem.setAlignment(Element.ALIGN_LEFT);

                    document.add(imagem);

                } catch (Exception e) {

                    JOptionPane.showMessageDialog(null, "Imagem não encontrada: " + e.getMessage());

                }



                // Adiciona informações da venda

                document.add(new Paragraph("********************************"));

                document.add(new Paragraph("   Cupom Não Fiscal   ", FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12)));

                document.add(new Paragraph("********************************"));

                document.add(new Paragraph("ID Venda: " + txtIdVenda.getText()));

                document.add(new Paragraph("Total   : " + txtTotalVenda.getText()));

                document.add(new Paragraph("Cliente : " + txtCliente.getText()));

                document.add(new Paragraph("Data    : " + txtDataVenda.getText()));

                document.add(new Paragraph("Obs.    : " + txtObs.getText()));

                document.add(new Paragraph("\nItens da Venda:"));

                document.add(new Paragraph("--------------------------------------------------------------------------------------------------------"));



                // Configura a tabela

                PdfPTable tabela = new PdfPTable(6); // Número de colunas

                tabela.setWidthPercentage(75); // % da Largura total da página

                tabela.setSpacingBefore(1f); //Acima

                tabela.setSpacingAfter(1f);  //Abaixo

                tabela.setWidths(new float[]{2f, 5f, 3f, 3f, 4f, 5f}); // Largura de cada coluna (fração da largura da página)

                tabela.setHorizontalAlignment(Element.ALIGN_LEFT); // Alinha a tabela à esquerda



                // Cabeçalho da tabela

                tabela.addCell(getCell("Cod", PdfPCell.ALIGN_LEFT));

                tabela.addCell(getCell("Produto", PdfPCell.ALIGN_LEFT));

                tabela.addCell(getCell("Qtd", PdfPCell.ALIGN_CENTER));

                tabela.addCell(getCell("Preço", PdfPCell.ALIGN_CENTER));

                tabela.addCell(getCell("SubTotal", PdfPCell.ALIGN_CENTER));

                tabela.addCell(getCell("Acumulado", PdfPCell.ALIGN_CENTER));



                // Adiciona os itens da venda

                DefaultTableModel model = (DefaultTableModel) Carrinho.getModel();

                for (int i = 0; i < model.getRowCount(); i++) {

                    tabela.addCell(getCell(model.getValueAt(i, 0).toString(), PdfPCell.ALIGN_LEFT)); // Código

                    tabela.addCell(getCell(model.getValueAt(i, 1).toString(), PdfPCell.ALIGN_LEFT)); // Produto



                    // Formata a quantidade

                    String quantidadeStr = model.getValueAt(i, 2).toString().replace(',', '.'); // Troca a vírgula pelo ponto

                    double quantidade = Double.parseDouble(quantidadeStr);

                    String quantidadeFormatada = String.format("%.3f", quantidade);

                    tabela.addCell(getCell(quantidadeFormatada, PdfPCell.ALIGN_CENTER)); // Qtd



                    tabela.addCell(getCell(model.getValueAt(i, 3).toString(), PdfPCell.ALIGN_CENTER)); // Preço

                    tabela.addCell(getCell(model.getValueAt(i, 4).toString(), PdfPCell.ALIGN_CENTER)); // SubTotal

                    

                    tabela.addCell(getCell(model.getValueAt(i, 5).toString(), PdfPCell.ALIGN_CENTER)); // Acumulado 

                }



                // Adiciona a tabela ao documento

                document.add(tabela);

                document.add(new Paragraph("==========================================================="));



            } catch (DocumentException | IOException e) {

                JOptionPane.showMessageDialog(null, "Erro ao gerar o PDF: " + e.getMessage());

                e.printStackTrace();

            } finally {

                // Fecha o documento

                document.close();

                JOptionPane.showMessageDialog(null, "PDF gerado com sucesso: " + file_name);

            }

        }

    }



    // Função auxiliar para criar células sem borda

    private PdfPCell getCell(String text, int alignment) {

        PdfPCell cell = new PdfPCell(new Phrase(text));

        cell.setPadding(5);

        cell.setHorizontalAlignment(alignment);

        cell.setBorder(PdfPCell.NO_BORDER);

        return cell;

    }





