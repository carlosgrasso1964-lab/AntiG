    public void exibirGrafico() throws ParseException {

        try {

            // Criar dataset para o gráfico de Gantt

            TaskSeriesCollection dataset = createDatasetFromTable(tabelaProj.getModel());



            // Criar gráfico

            JFreeChart chart = ChartFactory.createGanttChart(

                    "Gráfico de Gantt",

                    "Projeto/Etapa",

                    "Tempo",

                    dataset,

                    true,

                    true,

                    false

            );



            // Configurar eixo de tempo

            CategoryPlot plot = chart.getCategoryPlot();

            DateAxis rangeAxis = (DateAxis) plot.getRangeAxis();

            SimpleDateFormat dateFormat = new SimpleDateFormat("dd/MM/yyyy");

            rangeAxis.setDateFormatOverride(dateFormat);



            // Definir intervalo do eixo de tempo

            Date minDate = null;

            Date maxDate = null;

            for (int i = 0; i < dataset.getSeriesCount(); i++) {

                TaskSeries series = dataset.getSeries(i);

                for (Object obj : series.getTasks()) {

                    if (obj instanceof Task) {

                        Task task = (Task) obj;

                        Date start = task.getDuration().getStart();

                        Date end = task.getDuration().getEnd();

                        if (minDate == null || start.before(minDate)) {

                            minDate = start;

                        }

                        if (maxDate == null || end.after(maxDate)) {

                            maxDate = end;

                        }

                    }

                }

            }

            if (minDate != null && maxDate != null) {

                // Adicionar margem de 1 dia antes e depois

                long oneDay = 24 * 60 * 60 * 1000L;

                rangeAxis.setRange(new Date(minDate.getTime() - oneDay), new Date(maxDate.getTime() + oneDay));

            }



            // Mover eixo de tempo para a parte inferior

            plot.setRangeAxisLocation(AxisLocation.BOTTOM_OR_RIGHT);



            // Mover legenda para a parte inferior

            LegendTitle legend = chart.getLegend();

            legend.setPosition(RectangleEdge.BOTTOM);



            // Exibir gráfico

            ChartFrame frame = new ChartFrame("Gráfico de Gantt", chart);

            frame.pack();

            frame.setVisible(true);



            // Centralizar a janela

            Dimension screenSize = Toolkit.getDefaultToolkit().getScreenSize();

            int x = (screenSize.width - frame.getWidth()) / 2;

            int y = (screenSize.height - frame.getHeight()) / 2;

            frame.setLocation(x, y);



        } catch (ParseException e) {

            e.printStackTrace();

            JOptionPane.showMessageDialog(this, "Erro ao parsear datas: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);

        }

    }



    private TaskSeriesCollection createDatasetFromTable(TableModel model) throws ParseException {

        TaskSeriesCollection dataset = new TaskSeriesCollection();

        SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");

        dateFormat.setLenient(false); // Validação rigorosa de datas



        if (model instanceof ProjetosEtapasHierarquicoTableModel) {

            ProjetosEtapasHierarquicoTableModel hierarquicoModel = (ProjetosEtapasHierarquicoTableModel) model;

            List<ProjetoEtapaHierarquico> dados = hierarquicoModel.getDados();



            for (ProjetoEtapaHierarquico projetoEtapa : dados) {

                Object[] projeto = projetoEtapa.getProjeto();

                List<Object[]> etapas = projetoEtapa.getEtapas();



                // Adiciona o projeto

                TaskSeries seriesProjeto = new TaskSeries((String) projeto[1]); // Nome do projeto

                Date projetoInicioPrevisto = null;

                Date projetoFimPrevisto = null;

                Date projetoInicioRealizado = null;

                Date projetoFimRealizado = null;



                // Log para depuração

                //System.out.println("Projeto: " + projeto[1]);

                //System.out.println("Início Previsto: " + projeto[2]);

                //System.out.println("Fim Previsto: " + projeto[3]);

                if (projeto[2] != null && !((String) projeto[2]).isEmpty()) {

                    try {

                        projetoInicioPrevisto = dateFormat.parse((String) projeto[2]);

                        //System.out.println("Início Previsto Parseado: " + projetoInicioPrevisto);

                    } catch (ParseException e) {

                        System.err.println("Erro ao parsear Início Previsto: " + projeto[2]);

                        e.printStackTrace();

                    }

                }

                if (projeto[3] != null && !((String) projeto[3]).isEmpty()) {

                    try {

                        projetoFimPrevisto = dateFormat.parse((String) projeto[3]);

                        //System.out.println("Fim Previsto Parseado: " + projetoFimPrevisto);

                    } catch (ParseException e) {

                        System.err.println("Erro ao parsear Fim Previsto: " + projeto[3]);

                        e.printStackTrace();

                    }

                }

                if (projeto[4] != null && !((String) projeto[4]).isEmpty()) {

                    try {

                        projetoInicioRealizado = dateFormat.parse((String) projeto[4]);

                        //System.out.println("Início Realizado Parseado: " + projetoInicioRealizado);

                    } catch (ParseException e) {

                        System.err.println("Erro ao parsear Início Realizado: " + projeto[4]);

                        e.printStackTrace();

                    }

                }

                if (projeto[5] != null && !((String) projeto[5]).isEmpty()) {

                    try {

                        projetoFimRealizado = dateFormat.parse((String) projeto[5]);

                        //System.out.println("Fim Realizado Parseado: " + projetoFimRealizado);

                    } catch (ParseException e) {

                        System.err.println("Erro ao parsear Fim Realizado: " + projeto[5]);

                        e.printStackTrace();

                    }

                }



                // Ajuste temporário: usar a data final da última etapa como data final do projeto

                Date ultimaEtapaFimPrevisto = null;

                for (Object[] etapa : etapas) {

                    if (etapa[4] != null && !((String) etapa[4]).isEmpty()) {

                        try {

                            Date etapaFimPrevisto = dateFormat.parse((String) etapa[4]);

                            if (ultimaEtapaFimPrevisto == null || etapaFimPrevisto.after(ultimaEtapaFimPrevisto)) {

                                ultimaEtapaFimPrevisto = etapaFimPrevisto;

                            }

                        } catch (ParseException e) {

                            System.err.println("Erro ao parsear Fim Previsto da Etapa: " + etapa[4]);

                            e.printStackTrace();

                        }

                    }

                }

                if (ultimaEtapaFimPrevisto != null && (projetoFimPrevisto == null || ultimaEtapaFimPrevisto.before(projetoFimPrevisto))) {

                    projetoFimPrevisto = ultimaEtapaFimPrevisto;

                    //System.out.println("Ajuste: Fim Previsto do Projeto alterado para: " + projetoFimPrevisto);

                }



                if (projetoInicioPrevisto != null && projetoFimPrevisto != null) {

                    seriesProjeto.add(new Task("Previsto", new org.jfree.data.time.SimpleTimePeriod(projetoInicioPrevisto, projetoFimPrevisto)));

                }

                if (projetoInicioRealizado != null && projetoFimRealizado != null) {

                    seriesProjeto.add(new Task("Realizado", new org.jfree.data.time.SimpleTimePeriod(projetoInicioRealizado, projetoFimRealizado)));

                }

                dataset.add(seriesProjeto);



                // Adiciona as etapas

                for (Object[] etapa : etapas) {

                    TaskSeries seriesEtapa = new TaskSeries("  " + (String) etapa[0]); // Nome da etapa

                    Date etapaInicioPrevisto = null;

                    Date etapaFimPrevisto = null;

                    Date etapaInicioRealizado = null;

                    Date etapaFimRealizado = null;



                    // Log para depuração

                    //System.out.println("Etapa: " + etapa[0]);

                    //System.out.println("Início Previsto: " + etapa[3]);

                    //System.out.println("Fim Previsto: " + etapa[4]);

                    if (etapa[3] != null && !((String) etapa[3]).isEmpty()) {

                        try {

                            etapaInicioPrevisto = dateFormat.parse((String) etapa[3]);

                            //System.out.println("Início Previsto Parseado: " + etapaInicioPrevisto);

                        } catch (ParseException e) {

                            System.err.println("Erro ao parsear Início Previsto: " + etapa[3]);

                            e.printStackTrace();

                        }

                    }

                    if (etapa[4] != null && !((String) etapa[4]).isEmpty()) {

                        try {

                            etapaFimPrevisto = dateFormat.parse((String) etapa[4]);

                            //System.out.println("Fim Previsto Parseado: " + etapaFimPrevisto);

                        } catch (ParseException e) {

                            System.err.println("Erro ao parsear Fim Previsto: " + etapa[4]);

                            e.printStackTrace();

                        }

                    }

                    if (etapa[5] != null && !((String) etapa[5]).isEmpty()) {

                        try {

                            etapaInicioRealizado = dateFormat.parse((String) etapa[5]);

                            //System.out.println("Início Realizado Parseado: " + etapaInicioRealizado);

                        } catch (ParseException e) {

                            System.err.println("Erro ao parsear Início Realizado: " + etapa[5]);

                            e.printStackTrace();

                        }

                    }

                    if (etapa[6] != null && !((String) etapa[6]).isEmpty()) {

                        try {

                            etapaFimRealizado = dateFormat.parse((String) etapa[6]);

                            //System.out.println("Fim Realizado Parseado: " + etapaFimRealizado);

                        } catch (ParseException e) {

                            System.err.println("Erro ao parsear Fim Realizado: " + etapa[6]);

                            e.printStackTrace();

                        }

                    }



                    if (etapaInicioPrevisto != null && etapaFimPrevisto != null) {

                        seriesEtapa.add(new Task("Previsto", new org.jfree.data.time.SimpleTimePeriod(etapaInicioPrevisto, etapaFimPrevisto)));

                    }

                    if (etapaInicioRealizado != null && etapaFimRealizado != null) {

                        seriesEtapa.add(new Task("Realizado", new org.jfree.data.time.SimpleTimePeriod(etapaInicioRealizado, etapaFimRealizado)));

                    }

                    dataset.add(seriesEtapa);

                }

            }

        }

        return dataset;

    }



