            JOptionPane.showMessageDialog(this, "Por favor, insira um ID válido (número inteiro).", "Erro", JOptionPane.ERROR_MESSAGE);

            tabelaProj.setModel(new ProjetosEtapasHierarquicoTableModel("")); // Volta para a exibição padrão

