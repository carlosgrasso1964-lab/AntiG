    public class GraficoDeLinha extends ApplicationFrame {



        public GraficoDeLinha(String title) {

            super(title);

        }



        public void criarGrafico(DefaultTableModel tableModel) {

            DefaultCategoryDataset dataset = new DefaultCategoryDataset();



            // Percorre as linhas da tabela para pegar as datas e os saldos

            for (int i = 0; i < tableModel.getRowCount(); i++) {

                String data = (String) tableModel.getValueAt(i, 7); // Coluna de data

                String saldoStr = (String) tableModel.getValueAt(i, 16); // Coluna de saldo



                // Verifica se o saldo é vazio, nulo ou contém apenas espaços em branco

                if (saldoStr != null && !saldoStr.trim().isEmpty()) {

                    try {

                        // Remove os separadores de milhar (pontos) e substitui a vírgula decimal por ponto

                        double saldo = Double.parseDouble(saldoStr.replace(".", "").replace(",", "."));

                        dataset.addValue(saldo, "Saldo", data); // Adiciona o saldo no dataset

                    } catch (NumberFormatException e) {

                        System.err.println("Erro ao converter o saldo: " + saldoStr);

                    }

                } else {

                    //System.err.println("Saldo vazio ou nulo na linha: " + i + " - data: " + data);

                }

            }



            // Cria o gráfico de linha

            JFreeChart lineChart = ChartFactory.createLineChart(

                    "Evolução do Saldo no Período",

                    "Data", // Eixo X

                    "Saldo", // Eixo Y

                    dataset,

                    PlotOrientation.VERTICAL,

                    true, true, false);



            // Personalizar o gráfico (ajustar a aparência das datas no eixo X)

            CategoryPlot plot = lineChart.getCategoryPlot();

            CategoryAxis domainAxis = plot.getDomainAxis();



            // Rotacionar os rótulos para melhorar a legibilidade

            domainAxis.setCategoryLabelPositions(CategoryLabelPositions.UP_45);



            // Reduzir o tamanho da fonte das labels no eixo X

            domainAxis.setTickLabelFont(new Font("Tahoma", Font.PLAIN, 10));



            // Exibe o gráfico em um JFrame no centro da tela

            ChartPanel chartPanel = new ChartPanel(lineChart);

            chartPanel.setPreferredSize(new java.awt.Dimension(800, 600));



            // Exibe o gráfico em uma janela

            JFrame frame = new JFrame("Gráfico de Saldo");

            frame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE); // Alterado de EXIT_ON_CLOSE para DISPOSE_ON_CLOSE

            frame.getContentPane().add(chartPanel);

            frame.pack();

            frame.setLocationRelativeTo(null); // Centraliza a janela

            frame.setVisible(true);

        }

    }

