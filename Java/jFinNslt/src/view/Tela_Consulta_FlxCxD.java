    public static String getDayOfWeek(String data) {



        try {

            SimpleDateFormat parser = new SimpleDateFormat("dd/MM/yyyy");

            parser.setLenient(false);

            Calendar cal = Calendar.getInstance();

            cal.setTime(parser.parse(data));

            @SuppressWarnings("deprecation")

            SimpleDateFormat dayFormat = new SimpleDateFormat("EEE", new Locale("pt", "BR")); // Formato abreviado do dia da semana

            String dayOfWeek = dayFormat.format(cal.getTime());

            return dayOfWeek.replace(".", ""); // Remover ponto final

        } catch (ParseException e) {

        }

        return "---";

    }



