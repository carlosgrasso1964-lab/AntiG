    private String formatarData(String dataString, SimpleDateFormat sdfSaida, SimpleDateFormat sdfEntrada) {

        // Verifica se é nulo, vazio ou se contém a string "null" (comum em alguns drivers JDBC)

        if (dataString == null || dataString.trim().isEmpty() || dataString.equalsIgnoreCase("null")) {

            return "";

        }

        try {

            Date dataUtil = sdfEntrada.parse(dataString);

            return sdfSaida.format(dataUtil);

        } catch (ParseException e) {

            // Em relatórios, às vezes é melhor retornar vazio do que "Data inválida" 

            // para não poluir o visual, mas manter o log para o desenvolvedor.

            return "";

        }

    }



