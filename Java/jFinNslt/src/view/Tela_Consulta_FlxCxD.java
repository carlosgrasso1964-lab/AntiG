    private void PegaSaldoAnterior() {

        //String sql = "SELECT SUM(Valor) FROM tbmovimento WHERE dtlancto <= ? AND vrecurso in ('1.001.001','1.001.002', '1.003.001') AND recurso not in('0079','0022')";
        String sql = "SELECT SUM(Valor) FROM tbmovimento WHERE dtlancto <= ? AND vrecurso in ('1.001.001','1.001.002') AND recurso not in('0079','0022')";
        try {

            conexao.abrirConexao(); // Abre a conexão

            try (Connection con = conexao.getConexao(); // Obtém a conexão

                PreparedStatement stt = con.prepareStatement(sql)            ) {

                String dataTexto = jFormattedTextFieldDataIni.getText();

                SimpleDateFormat formatoEntrada = new SimpleDateFormat("dd/MM/yyyy");

                Date data = formatoEntrada.parse(dataTexto);

                SimpleDateFormat formatoBanco = new SimpleDateFormat("yyyy-MM-dd");

                String dataFormatada = formatoBanco.format(data);

                stt.setString(1, dataFormatada);

                try (ResultSet rsoma = stt.executeQuery()) {

                    double somaval = 0;

                    while (rsoma.next()) {

                        somaval = rsoma.getDouble(1);

                    }

                    jTextFieldSaldoAnterior.setText(String.valueOf(somaval));

                }

            }

        } catch (SQLException | ParseException ex) {

            Logger.getLogger(Tela_Consulta_FlxCxD.class.getName()).log(Level.SEVERE, null, ex);

        } finally {

            conexao.fecharConexao(); // Fecha a conexão no final

        }

    }





